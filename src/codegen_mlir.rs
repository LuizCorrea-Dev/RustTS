use crate::ast::*;
use std::collections::{HashMap, HashSet};

/// Gerador de Código MLIR SSA (`rtsc --target=mlir` — v1.8.0-rts Cycle 2 Phase 6).
/// Traduz a AST tipada e verificada da RustTS para os dialetos canônicos do ecossistema MLIR
/// (`func`, `scf`, `memref`, `arith`, `vector`) combinados com atributos de segurança e layout
/// do dialeto `rts` (`rts.cap`, `rts.simd_tile`, `llvm.noalias`, `llvm.align = 64`).
pub struct MlirCodegen;

#[derive(Clone, Default)]
struct MlirLoweringCtx {
    ssa_counter: usize,
    mod_prefix: String,
    module_fn_names: HashSet<String>,
    extern_fns: HashMap<String, (Vec<bool>, Vec<String>, Option<String>)>,
    fn_return_types: HashMap<String, Option<String>>,
    fn_param_types: HashMap<String, Vec<String>>,
    struct_field_types: HashMap<(String, String), String>,
    var_ssa: HashMap<String, (String, String)>,
    local_struct_names: HashMap<String, String>,
    soa_columns: HashMap<String, (String, bool)>,
    arena_params: HashMap<String, (String, String)>,
    hw_cap_params: HashMap<String, CapabilityKind>,
}

impl MlirLoweringCtx {
    fn next_ssa(&mut self) -> String {
        let id = self.ssa_counter;
        self.ssa_counter += 1;
        format!("%{}", id)
    }
}

impl MlirCodegen {
    pub fn emit_mlir(module: &Module) -> String {
        let mut out = String::new();
        let mod_name = if module.path.is_empty() {
            "root".to_string()
        } else {
            module.path.join("_")
        };

        out.push_str(&format!(
            "// ==========================================================================\n\
             // Generated by rtsc 1.8.0-rts --target=mlir (Deterministic SSA & SoA Dialect)\n\
             // Source Module: {}\n\
             // Dialects: builtin, func, scf, memref, arith, vector, rts\n\
             // Guarantees:\n\
             //   1. 64-Byte Aligned SoA memref descriptors with llvm.noalias\n\
             //   2. Explicit Capability Contracts (@sealed_sig / @open_sig) in Function IR\n\
             //   3. Strip-Mined SIMD scf.for loops (rts.simd_tile = 256, width = 8)\n\
             // ==========================================================================\n\n",
            module.path.join(".")
        ));

        out.push_str(&format!(
            "module @{} attributes {{\n  \
             rts.compiler = \"1.8.0-rts\",\n  \
             rts.memory_model = \"scoped_arenas_o1\",\n  \
             rts.soa_alignment = 64 : i64\n\
             }} {{\n\n",
            mod_name
        ));

        let mut struct_field_types: HashMap<(String, String), String> = HashMap::new();
        let mut module_fn_names: HashSet<String> = HashSet::new();
        let mut fn_return_types: HashMap<String, Option<String>> = HashMap::new();
        let mut fn_param_types: HashMap<String, Vec<String>> = HashMap::new();
        let mut extern_fns: HashMap<String, (Vec<bool>, Vec<String>, Option<String>)> =
            HashMap::new();

        // 1. Metadados de Structs e Componentes SoA (64-Byte Cache Line Layout)
        for item in &module.items {
            if let Item::Struct(s) = item {
                let is_comp = s
                    .attributes
                    .iter()
                    .any(|a| matches!(a, Attribute::Component));
                let mut field_descs = Vec::new();
                for f in &s.fields {
                    let mlir_ty = Self::map_mlir_type(&f.ty);
                    struct_field_types.insert((s.name.clone(), f.name.clone()), mlir_ty.clone());
                    field_descs.push(format!("{}: {}", f.name, mlir_ty));
                }
                if is_comp {
                    out.push_str(&format!(
                        "  // @component struct {} (64B SoA Column Layout: {})\n",
                        s.name,
                        field_descs.join(", ")
                    ));
                } else {
                    out.push_str(&format!(
                        "  // struct {} ({})\n",
                        s.name,
                        field_descs.join(", ")
                    ));
                }
            }
        }

        // 2. Pré-coleta de assinaturas de funções e declarações `extern "C" fn`
        for item in &module.items {
            match item {
                Item::Function(f) => {
                    module_fn_names.insert(f.name.clone());
                    let ret_mlir = f.return_type.as_ref().map(Self::map_mlir_type);
                    fn_return_types.insert(f.name.clone(), ret_mlir);
                    let p_types: Vec<String> = f
                        .params
                        .iter()
                        .map(|p| Self::map_param_mlir_type(p))
                        .collect();
                    fn_param_types.insert(f.name.clone(), p_types);
                }
                Item::ExternFn(ext) => {
                    let mut cap_mask = Vec::new();
                    let mut runtime_param_types = Vec::new();
                    let mut req_caps = Vec::new();
                    for p in &ext.params {
                        if p.is_cap {
                            cap_mask.push(true);
                            if let Some(cap) = &p.capability {
                                req_caps.push(format!("\"{}\"", cap));
                            }
                        } else {
                            cap_mask.push(false);
                            runtime_param_types.push(Self::map_mlir_type(&p.ty));
                        }
                    }
                    let ret_mlir = ext.return_type.as_ref().map(Self::map_mlir_type);
                    extern_fns.insert(
                        ext.name.clone(),
                        (
                            cap_mask,
                            runtime_param_types.clone(),
                            ret_mlir.clone(),
                        ),
                    );
                    fn_return_types.insert(ext.name.clone(), ret_mlir.clone());

                    let ret_sig = match &ret_mlir {
                        Some(r) => format!(" -> {}", r),
                        None => String::new(),
                    };
                    out.push_str(&format!(
                        "  func.func private @{}({}){} attributes {{ llvm.emit_c_interface, rts.ffi_abi = \"{}\", rts.required_caps = [{}] }}\n",
                        ext.name,
                        runtime_param_types.join(", "),
                        ret_sig,
                        ext.abi,
                        req_caps.join(", ")
                    ));
                }
                _ => {}
            }
        }

        if !extern_fns.is_empty() {
            out.push('\n');
        }

        // 3. Emissão de Funções e Sistemas (`func.func`)
        for item in &module.items {
            if let Item::Function(f) = item {
                let mut ctx = MlirLoweringCtx {
                    ssa_counter: 0,
                    mod_prefix: mod_name.clone(),
                    module_fn_names: module_fn_names.clone(),
                    extern_fns: extern_fns.clone(),
                    fn_return_types: fn_return_types.clone(),
                    fn_param_types: fn_param_types.clone(),
                    struct_field_types: struct_field_types.clone(),
                    ..Default::default()
                };

                let mut mlir_params = Vec::new();
                for p in &f.params {
                    let p_ssa = format!("%{}", p.name);
                    let p_ty = Self::map_param_mlir_type(p);
                    ctx.var_ssa.insert(p.name.clone(), (p_ssa.clone(), p_ty.clone()));

                    if let TypeExpr::Named { name, .. } = &p.ty {
                        ctx.local_struct_names.insert(p.name.clone(), name.clone());
                    }

                    if let Some(cap) = &p.capability {
                        ctx.hw_cap_params.insert(p.name.clone(), cap.kind.clone());
                        match (&cap.kind, &cap.generic_arg) {
                            (CapabilityKind::MutColumn, Some(CapGenericArg::TypeName(t))) => {
                                ctx.soa_columns.insert(p.name.clone(), (t.clone(), true));
                                mlir_params.push(format!(
                                    "{}: {} {{rts.cap = \"MutColumn<{}>\", rts.access = \"read_write\", llvm.noalias, llvm.align = 64 : i64}}",
                                    p_ssa, p_ty, t
                                ));
                            }
                            (CapabilityKind::ReadColumn, Some(CapGenericArg::TypeName(t))) => {
                                ctx.soa_columns.insert(p.name.clone(), (t.clone(), false));
                                mlir_params.push(format!(
                                    "{}: {} {{rts.cap = \"ReadColumn<{}>\", rts.access = \"read_only\", llvm.noalias, llvm.align = 64 : i64}}",
                                    p_ssa, p_ty, t
                                ));
                            }
                            (CapabilityKind::ScopedArena(scope), elem_opt)
                            | (CapabilityKind::ReadScopedArena(scope), elem_opt) => {
                                let elem_name = match elem_opt {
                                    Some(CapGenericArg::TypeName(t)) => t.clone(),
                                    _ => "byte".to_string(),
                                };
                                let rank = scope.rank();
                                ctx.arena_params.insert(
                                    p.name.clone(),
                                    (cap.domain_name.clone(), elem_name),
                                );
                                mlir_params.push(format!(
                                    "{}: {} {{rts.cap = \"{}\", rts.arena_rank = {} : i32}}",
                                    p_ssa, p_ty, cap, rank
                                ));
                            }
                            _ => {
                                mlir_params.push(format!(
                                    "{}: {} {{rts.cap = \"{}\"}}",
                                    p_ssa, p_ty, cap
                                ));
                            }
                        }
                    } else {
                        mlir_params.push(format!("{}: {}", p_ssa, p_ty));
                    }
                }

                let visibility = if f.is_pub { "public" } else { "private" };
                let fn_sym = if f.name == "main" {
                    "main".to_string()
                } else {
                    format!("{}_{}", mod_name, f.name)
                };

                let ret_mlir = f.return_type.as_ref().map(Self::map_mlir_type);
                let ret_sig = match &ret_mlir {
                    Some(r) => format!(" -> {}", r),
                    None => String::new(),
                };

                let is_open_sig = f
                    .attributes
                    .iter()
                    .any(|a| matches!(a, Attribute::OpenSig));
                let contract = if is_open_sig { "open_sig" } else { "sealed_sig" };

                let mut fn_attrs = vec![format!("rts.contract = \"{}\"", contract)];
                for attr in &f.attributes {
                    match attr {
                        Attribute::System { stage } => {
                            fn_attrs.push(format!("rts.system_stage = \"{}\"", stage));
                            fn_attrs.push(
                                "rts.execution = \"deterministic_single_thread\"".to_string(),
                            );
                        }
                        Attribute::ParallelSystem { stage } => {
                            fn_attrs.push(format!("rts.system_stage = \"{}\"", stage));
                            fn_attrs
                                .push("rts.execution = \"lock_free_parallel_tiles\"".to_string());
                        }
                        Attribute::GpuKernel => {
                            fn_attrs.push("rts.gpu_kernel = true".to_string());
                        }
                        _ => {}
                    }
                }

                out.push_str(&format!(
                    "  func.func {} @{}({}){} attributes {{ {} }} {{\n",
                    visibility,
                    fn_sym,
                    mlir_params.join(", "),
                    ret_sig,
                    fn_attrs.join(", ")
                ));

                let mut ended_with_return = false;
                for stmt in &f.body {
                    if matches!(stmt, Stmt::Return { .. }) {
                        ended_with_return = true;
                    }
                    Self::lower_stmt(&mut out, stmt, 2, &mut ctx, &ret_mlir);
                }

                if !ended_with_return {
                    if let Some(r_ty) = &ret_mlir {
                        let def_ssa = ctx.next_ssa();
                        if r_ty == "f32" || r_ty == "f64" {
                            out.push_str(&format!(
                                "    {} = arith.constant 0.0 : {}\n",
                                def_ssa, r_ty
                            ));
                        } else {
                            out.push_str(&format!(
                                "    {} = arith.constant 0 : {}\n",
                                def_ssa, r_ty
                            ));
                        }
                        out.push_str(&format!("    func.return {} : {}\n", def_ssa, r_ty));
                    } else {
                        out.push_str("    func.return\n");
                    }
                }

                out.push_str("  }\n\n");
            }
        }

        out.push_str("}\n");
        out
    }

    fn lower_stmt(
        out: &mut String,
        stmt: &Stmt,
        indent: usize,
        ctx: &mut MlirLoweringCtx,
        fn_ret: &Option<String>,
    ) {
        let pad = "  ".repeat(indent);
        match stmt {
            Stmt::Let {
                name, ty, value, ..
            } => {
                if let Some(TypeExpr::Capability(cap_spec)) = ty {
                    let cap_ty = format!("!rts.cap<\"{}\">", cap_spec.domain_name);
                    let ssa = ctx.next_ssa();
                    out.push_str(&format!(
                        "{}{} = \"rts.root_cap_init\"() {{cap = \"{}\"}} : () -> {}\n",
                        pad, ssa, cap_spec, cap_ty
                    ));
                    ctx.hw_cap_params.insert(name.clone(), cap_spec.kind.clone());
                    ctx.var_ssa.insert(name.clone(), (ssa, cap_ty));
                    return;
                }

                let explicit_mlir_ty = ty.as_ref().map(Self::map_mlir_type);
                let (val_ssa, inferred_ty) =
                    Self::lower_expr(out, value, indent, ctx, explicit_mlir_ty.as_deref());
                let final_ty = explicit_mlir_ty.unwrap_or(inferred_ty);

                if let Some(TypeExpr::Named { name: s_name, .. }) = ty {
                    ctx.local_struct_names.insert(name.clone(), s_name.clone());
                } else if let Expr::StructInit { struct_name, .. } = value {
                    ctx.local_struct_names
                        .insert(name.clone(), struct_name.clone());
                }

                ctx.var_ssa.insert(name.clone(), (val_ssa, final_ty));
            }

            Stmt::Assign { target, value, .. } => {
                // Caso 1: Escrita em coluna SoA `transforms[i].position = ...` ou `pos[i].px = ...`
                if let Expr::FieldAccess {
                    receiver, field, ..
                } = target
                {
                    if let Expr::Index {
                        receiver: col_expr,
                        index,
                        ..
                    } = receiver.as_ref()
                    {
                        if let Expr::Ident(col_name, _) = col_expr.as_ref() {
                            if ctx.soa_columns.contains_key(col_name) {
                                let (idx_ssa, idx_ty) =
                                    Self::lower_expr(out, index, indent, ctx, Some("index"));
                                let idx_final = Self::ensure_index_type(out, indent, ctx, &idx_ssa, &idx_ty);
                                let (val_ssa, _) =
                                    Self::lower_expr(out, value, indent, ctx, Some("f32"));
                                let col_ssa = ctx
                                    .var_ssa
                                    .get(col_name)
                                    .map(|(s, _)| s.clone())
                                    .unwrap_or_else(|| format!("%{}", col_name));
                                out.push_str(&format!(
                                    "{}memref.store {}, {}[{}] {{rts.field = \"{}\", rts.aligned = 64 : i64}} : memref<?xf32, strided<[1]>>\n",
                                    pad, val_ssa, col_ssa, idx_final, field
                                ));
                                return;
                            }
                        }
                    }
                    // Sub-componente vetorial `transforms[i].position.y = 0.0`
                    if let Expr::FieldAccess {
                        receiver: inner_rec,
                        field: vec_field,
                        ..
                    } = receiver.as_ref()
                    {
                        if let Expr::Index {
                            receiver: col_expr,
                            index,
                            ..
                        } = inner_rec.as_ref()
                        {
                            if let Expr::Ident(col_name, _) = col_expr.as_ref() {
                                if ctx.soa_columns.contains_key(col_name) {
                                    let (idx_ssa, idx_ty) =
                                        Self::lower_expr(out, index, indent, ctx, Some("index"));
                                    let idx_final =
                                        Self::ensure_index_type(out, indent, ctx, &idx_ssa, &idx_ty);
                                    let (val_ssa, _) =
                                        Self::lower_expr(out, value, indent, ctx, Some("f32"));
                                    let col_ssa = ctx
                                        .var_ssa
                                        .get(col_name)
                                        .map(|(s, _)| s.clone())
                                        .unwrap_or_else(|| format!("%{}", col_name));
                                    out.push_str(&format!(
                                        "{}memref.store {}, {}[{}] {{rts.field = \"{}.{}\", rts.aligned = 64 : i64}} : memref<?xf32, strided<[1]>>\n",
                                        pad, val_ssa, col_ssa, idx_final, vec_field, field
                                    ));
                                    return;
                                }
                            }
                        }
                    }
                }

                // Caso 2: Variável local mutável (`i = i + 1;`)
                if let Expr::Ident(var_name, _) = target {
                    let expected_ty = ctx.var_ssa.get(var_name).map(|(_, t)| t.clone());
                    let (val_ssa, val_ty) =
                        Self::lower_expr(out, value, indent, ctx, expected_ty.as_deref());
                    out.push_str(&format!(
                        "{}\"rts.ssa_assign\"({}) {{var = \"{}\"}} : ({}) -> ()\n",
                        pad, val_ssa, var_name, val_ty
                    ));
                    ctx.var_ssa.insert(var_name.clone(), (val_ssa, val_ty));
                    return;
                }

                let (val_ssa, val_ty) = Self::lower_expr(out, value, indent, ctx, None);
                out.push_str(&format!(
                    "{}\"rts.store_assign\"({}) : ({}) -> ()\n",
                    pad, val_ssa, val_ty
                ));
            }

            Stmt::ForRange {
                iterator,
                start,
                end,
                body,
                ..
            } => {
                let (s_ssa, s_ty) = Self::lower_expr(out, start, indent, ctx, Some("index"));
                let s_idx = Self::ensure_index_type(out, indent, ctx, &s_ssa, &s_ty);
                let (e_ssa, e_ty) = Self::lower_expr(out, end, indent, ctx, Some("index"));
                let e_idx = Self::ensure_index_type(out, indent, ctx, &e_ssa, &e_ty);
                let step_ssa = ctx.next_ssa();
                out.push_str(&format!(
                    "{}{} = arith.constant 1 : index\n",
                    pad, step_ssa
                ));

                let iter_ssa = format!("%{}", iterator);
                ctx.var_ssa
                    .insert(iterator.clone(), (iter_ssa.clone(), "index".to_string()));

                out.push_str(&format!(
                    "{}scf.for {} = {} to {} step {} {{\n",
                    pad, iter_ssa, s_idx, e_idx, step_ssa
                ));
                for s in body {
                    Self::lower_stmt(out, s, indent + 1, ctx, fn_ret);
                }
                out.push_str(&format!(
                    "{}}} {{rts.simd_tile = 256 : i32, rts.vectorize_width = 8 : i32}}\n",
                    pad
                ));
            }

            Stmt::If {
                condition,
                then_branch,
                else_branch,
                ..
            } => {
                let (cond_ssa, _) = Self::lower_expr(out, condition, indent, ctx, Some("i1"));
                out.push_str(&format!("{}scf.if {} {{\n", pad, cond_ssa));
                for s in then_branch {
                    Self::lower_stmt(out, s, indent + 1, ctx, fn_ret);
                }
                if let Some(eb) = else_branch {
                    out.push_str(&format!("{}}} else {{\n", pad));
                    for s in eb {
                        Self::lower_stmt(out, s, indent + 1, ctx, fn_ret);
                    }
                }
                out.push_str(&format!("{}}}\n", pad));
            }

            Stmt::While {
                condition, body, ..
            } => {
                out.push_str(&format!("{}scf.while : () -> () {{\n", pad));
                let (cond_ssa, _) = Self::lower_expr(out, condition, indent + 1, ctx, Some("i1"));
                out.push_str(&format!("{}  scf.condition({})\n", pad, cond_ssa));
                out.push_str(&format!("{}}} do {{\n", pad));
                for s in body {
                    Self::lower_stmt(out, s, indent + 1, ctx, fn_ret);
                }
                out.push_str(&format!("{}  scf.yield\n", pad));
                out.push_str(&format!("{}}}\n", pad));
            }

            Stmt::Match { expr, arms, .. } => {
                let (scrut_ssa, scrut_ty) = Self::lower_expr(out, expr, indent, ctx, None);
                out.push_str(&format!(
                    "{}\"rts.match\"({}) {{scrutinee_type = \"{}\"}} ({{\n",
                    pad, scrut_ssa, scrut_ty
                ));
                for arm in arms {
                    let pat_label = match &arm.pattern {
                        MatchPattern::Variant {
                            enum_name,
                            variant,
                            binding,
                        } => {
                            let prefix = enum_name
                                .as_ref()
                                .map(|e| format!("{}::", e))
                                .unwrap_or_default();
                            if let Some(b) = binding {
                                ctx.var_ssa
                                    .insert(b.clone(), (scrut_ssa.clone(), "f32".to_string()));
                            }
                            format!("{}{}", prefix, variant)
                        }
                        MatchPattern::Wildcard => "_".to_string(),
                    };
                    out.push_str(&format!("{}  // arm: {}\n", pad, pat_label));
                    for s in &arm.body {
                        Self::lower_stmt(out, s, indent + 1, ctx, fn_ret);
                    }
                }
                out.push_str(&format!("{}}}) : ({}) -> ()\n", pad, scrut_ty));
            }

            Stmt::Break { .. } => {
                out.push_str(&format!("{}\"rts.loop_break\"() : () -> ()\n", pad));
            }

            Stmt::Continue { .. } => {
                out.push_str(&format!("{}\"rts.loop_continue\"() : () -> ()\n", pad));
            }

            Stmt::Return {
                value: expr_opt, ..
            } => {
                if let Some(e) = expr_opt {
                    let (val_ssa, val_ty) =
                        Self::lower_expr(out, e, indent, ctx, fn_ret.as_deref());
                    let ret_ty = fn_ret.clone().unwrap_or(val_ty);
                    out.push_str(&format!("{}func.return {} : {}\n", pad, val_ssa, ret_ty));
                } else {
                    out.push_str(&format!("{}func.return\n", pad));
                }
            }

            Stmt::ExprStmt { expr: e, .. } => {
                let _ = Self::lower_expr(out, e, indent, ctx, None);
            }
        }
    }

    fn lower_expr(
        out: &mut String,
        expr: &Expr,
        indent: usize,
        ctx: &mut MlirLoweringCtx,
        expected_ty: Option<&str>,
    ) -> (String, String) {
        let pad = "  ".repeat(indent);
        match expr {
            Expr::IntLit(v, _) => {
                let ty = match expected_ty {
                    Some(t @ ("i8" | "i16" | "i32" | "i64" | "index")) => t.to_string(),
                    _ => "i32".to_string(),
                };
                let ssa = ctx.next_ssa();
                out.push_str(&format!("{}{} = arith.constant {} : {}\n", pad, ssa, v, ty));
                (ssa, ty)
            }
            Expr::FloatLit(v, _) => {
                let ty = match expected_ty {
                    Some("f64") => "f64".to_string(),
                    _ => "f32".to_string(),
                };
                let s = v.to_string();
                let formatted = if s.contains('.') {
                    s
                } else {
                    format!("{}.0", s)
                };
                let ssa = ctx.next_ssa();
                out.push_str(&format!(
                    "{}{} = arith.constant {} : {}\n",
                    pad, ssa, formatted, ty
                ));
                (ssa, ty)
            }
            Expr::BoolLit(b, _) => {
                let ssa = ctx.next_ssa();
                out.push_str(&format!("{}{} = arith.constant {} : i1\n", pad, ssa, b));
                (ssa, "i1".to_string())
            }
            Expr::StringLit(s, _) => {
                let ssa = ctx.next_ssa();
                let escaped = s.replace('"', "\\\"");
                out.push_str(&format!(
                    "{}{} = \"rts.constant_str\"() {{value = \"{}\"}} : () -> !rts.str\n",
                    pad, ssa, escaped
                ));
                (ssa, "!rts.str".to_string())
            }
            Expr::Ident(name, _) => {
                if let Some((ssa, ty)) = ctx.var_ssa.get(name) {
                    (ssa.clone(), ty.clone())
                } else {
                    (format!("%{}", name), "f32".to_string())
                }
            }
            Expr::Unary { op, expr: inner, .. } => match op {
                UnaryOp::Neg => {
                    let (in_ssa, in_ty) = Self::lower_expr(out, inner, indent, ctx, expected_ty);
                    let ssa = ctx.next_ssa();
                    if in_ty == "f32" || in_ty == "f64" {
                        out.push_str(&format!(
                            "{}{} = arith.negf {} : {}\n",
                            pad, ssa, in_ssa, in_ty
                        ));
                    } else {
                        let zero_ssa = ctx.next_ssa();
                        out.push_str(&format!(
                            "{}{} = arith.constant 0 : {}\n",
                            pad, zero_ssa, in_ty
                        ));
                        out.push_str(&format!(
                            "{}{} = arith.subi {}, {} : {}\n",
                            pad, ssa, zero_ssa, in_ssa, in_ty
                        ));
                    }
                    (ssa, in_ty)
                }
                UnaryOp::Not => {
                    let (in_ssa, _) = Self::lower_expr(out, inner, indent, ctx, Some("i1"));
                    let true_ssa = ctx.next_ssa();
                    let ssa = ctx.next_ssa();
                    out.push_str(&format!("{}{} = arith.constant true : i1\n", pad, true_ssa));
                    out.push_str(&format!(
                        "{}{} = arith.xori {}, {} : i1\n",
                        pad, ssa, in_ssa, true_ssa
                    ));
                    (ssa, "i1".to_string())
                }
            },
            Expr::Binary {
                left, op, right, ..
            } => {
                let (l_ssa, l_ty) = Self::lower_expr(out, left, indent, ctx, expected_ty);
                let (r_ssa, r_ty) = Self::lower_expr(out, right, indent, ctx, Some(&l_ty));
                let is_float =
                    l_ty == "f32" || l_ty == "f64" || r_ty == "f32" || r_ty == "f64" || l_ty.starts_with("vector<");
                let op_ty = if is_float {
                    if l_ty.starts_with("vector<") {
                        l_ty.clone()
                    } else if r_ty.starts_with("vector<") {
                        r_ty.clone()
                    } else if l_ty == "f64" || r_ty == "f64" {
                        "f64".to_string()
                    } else {
                        "f32".to_string()
                    }
                } else {
                    l_ty.clone()
                };

                let ssa = ctx.next_ssa();
                match op {
                    BinaryOp::Add => {
                        let mnemonic = if is_float { "arith.addf" } else { "arith.addi" };
                        out.push_str(&format!(
                            "{}{} = {} {}, {} : {}\n",
                            pad, ssa, mnemonic, l_ssa, r_ssa, op_ty
                        ));
                        (ssa, op_ty)
                    }
                    BinaryOp::Sub => {
                        let mnemonic = if is_float { "arith.subf" } else { "arith.subi" };
                        out.push_str(&format!(
                            "{}{} = {} {}, {} : {}\n",
                            pad, ssa, mnemonic, l_ssa, r_ssa, op_ty
                        ));
                        (ssa, op_ty)
                    }
                    BinaryOp::Mul => {
                        let mnemonic = if is_float { "arith.mulf" } else { "arith.muli" };
                        out.push_str(&format!(
                            "{}{} = {} {}, {} : {}\n",
                            pad, ssa, mnemonic, l_ssa, r_ssa, op_ty
                        ));
                        (ssa, op_ty)
                    }
                    BinaryOp::Div => {
                        let mnemonic = if is_float { "arith.divf" } else { "arith.divsi" };
                        out.push_str(&format!(
                            "{}{} = {} {}, {} : {}\n",
                            pad, ssa, mnemonic, l_ssa, r_ssa, op_ty
                        ));
                        (ssa, op_ty)
                    }
                    BinaryOp::Eq
                    | BinaryOp::NotEq
                    | BinaryOp::Lt
                    | BinaryOp::LtEq
                    | BinaryOp::Gt
                    | BinaryOp::GtEq => {
                        if is_float {
                            let pred = match op {
                                BinaryOp::Eq => "oeq",
                                BinaryOp::NotEq => "one",
                                BinaryOp::Lt => "olt",
                                BinaryOp::LtEq => "ole",
                                BinaryOp::Gt => "ogt",
                                BinaryOp::GtEq => "oge",
                                _ => "oeq",
                            };
                            out.push_str(&format!(
                                "{}{} = arith.cmpf {}, {}, {} : {}\n",
                                pad, ssa, pred, l_ssa, r_ssa, op_ty
                            ));
                        } else {
                            let pred = match op {
                                BinaryOp::Eq => "eq",
                                BinaryOp::NotEq => "ne",
                                BinaryOp::Lt => "slt",
                                BinaryOp::LtEq => "sle",
                                BinaryOp::Gt => "sgt",
                                BinaryOp::GtEq => "sge",
                                _ => "eq",
                            };
                            out.push_str(&format!(
                                "{}{} = arith.cmpi {}, {}, {} : {}\n",
                                pad, ssa, pred, l_ssa, r_ssa, op_ty
                            ));
                        }
                        (ssa, "i1".to_string())
                    }
                    BinaryOp::And => {
                        out.push_str(&format!(
                            "{}{} = arith.andi {}, {} : i1\n",
                            pad, ssa, l_ssa, r_ssa
                        ));
                        (ssa, "i1".to_string())
                    }
                    BinaryOp::Or => {
                        out.push_str(&format!(
                            "{}{} = arith.ori {}, {} : i1\n",
                            pad, ssa, l_ssa, r_ssa
                        ));
                        (ssa, "i1".to_string())
                    }
                }
            }
            Expr::FieldAccess {
                receiver, field, ..
            } => {
                // Caso A: Sub-componente vetorial em coluna SoA `transforms[i].position.y`
                if let Expr::FieldAccess {
                    receiver: inner_rec,
                    field: vec_field,
                    ..
                } = receiver.as_ref()
                {
                    if let Expr::Index {
                        receiver: col_expr,
                        index,
                        ..
                    } = inner_rec.as_ref()
                    {
                        if let Expr::Ident(col_name, _) = col_expr.as_ref() {
                            if ctx.soa_columns.contains_key(col_name) {
                                let (idx_ssa, idx_ty) =
                                    Self::lower_expr(out, index, indent, ctx, Some("index"));
                                let idx_final =
                                    Self::ensure_index_type(out, indent, ctx, &idx_ssa, &idx_ty);
                                let col_ssa = ctx
                                    .var_ssa
                                    .get(col_name)
                                    .map(|(s, _)| s.clone())
                                    .unwrap_or_else(|| format!("%{}", col_name));
                                let ssa = ctx.next_ssa();
                                out.push_str(&format!(
                                    "{}{} = memref.load {}[{}] {{rts.field = \"{}.{}\", rts.aligned = 64 : i64}} : memref<?xf32, strided<[1]>>\n",
                                    pad, ssa, col_ssa, idx_final, vec_field, field
                                ));
                                return (ssa, "f32".to_string());
                            }
                        }
                    }
                }

                // Caso B: Coluna SoA `velocities[i].linear` ou `pos[i].px`
                if let Expr::Index {
                    receiver: col_expr,
                    index,
                    ..
                } = receiver.as_ref()
                {
                    if let Expr::Ident(col_name, _) = col_expr.as_ref() {
                        if ctx.soa_columns.contains_key(col_name) {
                            let (idx_ssa, idx_ty) =
                                Self::lower_expr(out, index, indent, ctx, Some("index"));
                            let idx_final =
                                Self::ensure_index_type(out, indent, ctx, &idx_ssa, &idx_ty);
                            let col_ssa = ctx
                                .var_ssa
                                .get(col_name)
                                .map(|(s, _)| s.clone())
                                .unwrap_or_else(|| format!("%{}", col_name));
                            let ssa = ctx.next_ssa();
                            out.push_str(&format!(
                                "{}{} = memref.load {}[{}] {{rts.field = \"{}\", rts.aligned = 64 : i64}} : memref<?xf32, strided<[1]>>\n",
                                pad, ssa, col_ssa, idx_final, field
                            ));
                            return (ssa, "f32".to_string());
                        }
                    }
                }

                // Caso C: `time.fixed_delta` ou struct field normal
                let (rec_ssa, rec_ty) = Self::lower_expr(out, receiver, indent, ctx, None);
                if field == "fixed_delta" {
                    let ssa = ctx.next_ssa();
                    out.push_str(&format!(
                        "{}{} = \"rts.timestep_delta\"({}) : ({}) -> f32\n",
                        pad, ssa, rec_ssa, rec_ty
                    ));
                    return (ssa, "f32".to_string());
                }

                let mut f_ty = expected_ty.unwrap_or("f32").to_string();
                if let Expr::Ident(r_name, _) = receiver.as_ref() {
                    if let Some(s_name) = ctx.local_struct_names.get(r_name) {
                        if let Some(mapped) =
                            ctx.struct_field_types.get(&(s_name.clone(), field.clone()))
                        {
                            f_ty = mapped.clone();
                        }
                    }
                }
                let ssa = ctx.next_ssa();
                out.push_str(&format!(
                    "{}{} = \"rts.struct_extract\"({}) {{field = \"{}\"}} : ({}) -> {}\n",
                    pad, ssa, rec_ssa, field, rec_ty, f_ty
                ));
                (ssa, f_ty)
            }

            Expr::Index {
                receiver, index, ..
            } => {
                let (rec_ssa, rec_ty) = Self::lower_expr(out, receiver, indent, ctx, None);
                let (idx_ssa, idx_ty) = Self::lower_expr(out, index, indent, ctx, Some("index"));
                let idx_final = Self::ensure_index_type(out, indent, ctx, &idx_ssa, &idx_ty);
                let elem_ty = expected_ty.unwrap_or("f32").to_string();
                let ssa = ctx.next_ssa();
                out.push_str(&format!(
                    "{}{} = \"rts.index_load\"({}, {}) : ({}, index) -> {}\n",
                    pad, ssa, rec_ssa, idx_final, rec_ty, elem_ty
                ));
                (ssa, elem_ty)
            }

            Expr::MethodCall {
                receiver,
                method,
                args,
                ..
            } => {
                let (rec_ssa, rec_ty) = Self::lower_expr(out, receiver, indent, ctx, None);
                if method == "len" {
                    let ssa = ctx.next_ssa();
                    out.push_str(&format!(
                        "{}{} = \"rts.collection_len\"({}) : ({}) -> index\n",
                        pad, ssa, rec_ssa, rec_ty
                    ));
                    return (ssa, "index".to_string());
                }

                let mut arg_ssas = Vec::new();
                let mut arg_tys = Vec::new();
                for a in args {
                    let (a_s, a_t) = Self::lower_expr(out, a, indent, ctx, None);
                    arg_ssas.push(a_s);
                    arg_tys.push(a_t);
                }

                if let Expr::Ident(r_name, _) = receiver.as_ref() {
                    if ctx.arena_params.contains_key(r_name) && method == "push" {
                        out.push_str(&format!(
                            "{}\"rts.arena_push\"({}, {}) : ({}, {}) -> ()\n",
                            pad,
                            rec_ssa,
                            arg_ssas.join(", "),
                            rec_ty,
                            arg_tys.join(", ")
                        ));
                        return (rec_ssa, "()".to_string());
                    }
                    if let Some(hw_kind) = ctx.hw_cap_params.get(r_name).cloned() {
                        let ssa = ctx.next_ssa();
                        let ret_ty = match (hw_kind, method.as_str()) {
                            (CapabilityKind::I2CBus, "read_register_u16") => "i16".to_string(),
                            (CapabilityKind::I2CBus, "read_register_u8") => "i8".to_string(),
                            _ => expected_ty.unwrap_or("i32").to_string(),
                        };
                        let mut all_vals = vec![rec_ssa];
                        all_vals.extend(arg_ssas);
                        let mut all_tys = vec![rec_ty];
                        all_tys.extend(arg_tys);
                        out.push_str(&format!(
                            "{}{} = \"rts.hw_call\"({}) {{method = \"{}\"}} : ({}) -> {}\n",
                            pad,
                            ssa,
                            all_vals.join(", "),
                            method,
                            all_tys.join(", "),
                            ret_ty
                        ));
                        return (ssa, ret_ty);
                    }
                }

                if ctx.module_fn_names.contains(method) {
                    let mut all_vals = vec![rec_ssa];
                    all_vals.extend(arg_ssas);
                    let mut all_tys = vec![rec_ty];
                    all_tys.extend(arg_tys);
                    let ret_opt = ctx.fn_return_types.get(method).cloned().flatten();
                    let callee_sym = format!("{}_{}", ctx.mod_prefix, method);
                    if let Some(r_ty) = ret_opt {
                        let ssa = ctx.next_ssa();
                        out.push_str(&format!(
                            "{}{} = func.call @{}({}) : ({}) -> {}\n",
                            pad,
                            ssa,
                            callee_sym,
                            all_vals.join(", "),
                            all_tys.join(", "),
                            r_ty
                        ));
                        return (ssa, r_ty);
                    } else {
                        out.push_str(&format!(
                            "{}func.call @{}({}) : ({}) -> ()\n",
                            pad,
                            callee_sym,
                            all_vals.join(", "),
                            all_tys.join(", ")
                        ));
                        return ("%void".to_string(), "()".to_string());
                    }
                }

                let ret_ty = expected_ty.unwrap_or("f32").to_string();
                let ssa = ctx.next_ssa();
                let mut all_vals = vec![rec_ssa];
                all_vals.extend(arg_ssas);
                let mut all_tys = vec![rec_ty];
                all_tys.extend(arg_tys);
                out.push_str(&format!(
                    "{}{} = \"rts.method_call\"({}) {{method = \"{}\"}} : ({}) -> {}\n",
                    pad,
                    ssa,
                    all_vals.join(", "),
                    method,
                    all_tys.join(", "),
                    ret_ty
                ));
                (ssa, ret_ty)
            }

            Expr::StaticCall {
                namespace,
                func,
                args,
                ..
            } => {
                let mut arg_ssas = Vec::new();
                let mut arg_tys = Vec::new();
                for a in args {
                    let (a_s, a_t) = Self::lower_expr(out, a, indent, ctx, None);
                    arg_ssas.push(a_s);
                    arg_tys.push(a_t);
                }

                if namespace == "self"
                    && matches!(func.as_str(), "vec2" | "vec3" | "vec4" | "quat")
                {
                    let lanes = match func.as_str() {
                        "vec2" => 2,
                        "vec3" => 3,
                        _ => 4,
                    };
                    let vec_ty = format!("vector<{}xf32>", lanes);
                    let ssa = ctx.next_ssa();
                    out.push_str(&format!(
                        "{}{} = \"rts.vec_construct\"({}) : ({}) -> {}\n",
                        pad,
                        ssa,
                        arg_ssas.join(", "),
                        arg_tys.join(", "),
                        vec_ty
                    ));
                    return (ssa, vec_ty);
                }

                if let Some((cap_mask, ffi_tys, ret_opt)) = ctx.extern_fns.get(func).cloned() {
                    let filtered_vals: Vec<String> = arg_ssas
                        .into_iter()
                        .enumerate()
                        .filter(|(i, _)| !cap_mask.get(*i).copied().unwrap_or(false))
                        .map(|(_, v)| v)
                        .collect();
                    if let Some(r_ty) = ret_opt {
                        let ssa = ctx.next_ssa();
                        out.push_str(&format!(
                            "{}{} = func.call @{}({}) : ({}) -> {}\n",
                            pad,
                            ssa,
                            func,
                            filtered_vals.join(", "),
                            ffi_tys.join(", "),
                            r_ty
                        ));
                        return (ssa, r_ty);
                    } else {
                        out.push_str(&format!(
                            "{}func.call @{}({}) : ({}) -> ()\n",
                            pad,
                            func,
                            filtered_vals.join(", "),
                            ffi_tys.join(", ")
                        ));
                        return ("%void".to_string(), "()".to_string());
                    }
                }

                if ctx.module_fn_names.contains(func) {
                    let callee_sym = format!("{}_{}", ctx.mod_prefix, func);
                    let param_sig = ctx
                        .fn_param_types
                        .get(func)
                        .cloned()
                        .unwrap_or_else(|| arg_tys.clone());
                    let ret_opt = ctx.fn_return_types.get(func).cloned().flatten();
                    if let Some(r_ty) = ret_opt {
                        let ssa = ctx.next_ssa();
                        out.push_str(&format!(
                            "{}{} = func.call @{}({}) : ({}) -> {}\n",
                            pad,
                            ssa,
                            callee_sym,
                            arg_ssas.join(", "),
                            param_sig.join(", "),
                            r_ty
                        ));
                        return (ssa, r_ty);
                    } else {
                        out.push_str(&format!(
                            "{}func.call @{}({}) : ({}) -> ()\n",
                            pad,
                            callee_sym,
                            arg_ssas.join(", "),
                            param_sig.join(", ")
                        ));
                        return ("%void".to_string(), "()".to_string());
                    }
                }

                let ret_ty = expected_ty.unwrap_or("f32").to_string();
                let ssa = ctx.next_ssa();
                out.push_str(&format!(
                    "{}{} = \"rts.intrinsic_call\"({}) {{callee = \"{}::{}\"}} : ({}) -> {}\n",
                    pad,
                    ssa,
                    arg_ssas.join(", "),
                    namespace,
                    func,
                    arg_tys.join(", "),
                    ret_ty
                ));
                (ssa, ret_ty)
            }

            Expr::StructInit {
                struct_name,
                fields,
                ..
            } => {
                let mut f_ssas = Vec::new();
                let mut f_tys = Vec::new();
                for (f_name, f_expr) in fields {
                    let expected_f = ctx
                        .struct_field_types
                        .get(&(struct_name.clone(), f_name.clone()))
                        .cloned();
                    let (s, t) =
                        Self::lower_expr(out, f_expr, indent, ctx, expected_f.as_deref());
                    f_ssas.push(s);
                    f_tys.push(t);
                }
                let s_ty = format!("!rts.struct<\"{}\">", struct_name);
                let ssa = ctx.next_ssa();
                out.push_str(&format!(
                    "{}{} = \"rts.struct_construct\"({}) {{struct = \"{}\"}} : ({}) -> {}\n",
                    pad,
                    ssa,
                    f_ssas.join(", "),
                    struct_name,
                    f_tys.join(", "),
                    s_ty
                ));
                (ssa, s_ty)
            }

            Expr::EnumConstructor {
                enum_name,
                variant,
                payload,
                ..
            } => {
                let e_ty = expected_ty
                    .map(|s| s.to_string())
                    .or_else(|| enum_name.as_ref().map(|e| format!("!rts.enum<\"{}\">", e)))
                    .unwrap_or_else(|| "!rts.enum<\"Result\">".to_string());
                let ssa = ctx.next_ssa();
                if let Some(p) = payload {
                    let (p_s, p_t) = Self::lower_expr(out, p, indent, ctx, None);
                    out.push_str(&format!(
                        "{}{} = \"rts.enum_construct\"({}) {{variant = \"{}\"}} : ({}) -> {}\n",
                        pad, ssa, p_s, variant, p_t, e_ty
                    ));
                } else {
                    out.push_str(&format!(
                        "{}{} = \"rts.enum_construct\"() {{variant = \"{}\"}} : () -> {}\n",
                        pad, ssa, variant, e_ty
                    ));
                }
                (ssa, e_ty)
            }

            Expr::Cast {
                expr: inner,
                target_type,
                ..
            } => {
                let target_mlir = Self::map_mlir_type(target_type);
                let (in_ssa, in_ty) = Self::lower_expr(out, inner, indent, ctx, None);
                if in_ty == target_mlir {
                    return (in_ssa, target_mlir);
                }
                let ssa = ctx.next_ssa();
                out.push_str(&format!(
                    "{}{} = \"rts.cast\"({}) : ({}) -> {}\n",
                    pad, ssa, in_ssa, in_ty, target_mlir
                ));
                (ssa, target_mlir)
            }

            Expr::TryOp { expr: inner, .. } => {
                let (in_ssa, in_ty) = Self::lower_expr(out, inner, indent, ctx, expected_ty);
                let ok_ty = expected_ty.unwrap_or("i16").to_string();
                let ssa = ctx.next_ssa();
                out.push_str(&format!(
                    "{}{} = \"rts.try_unwrap\"({}) : ({}) -> {}\n",
                    pad, ssa, in_ssa, in_ty, ok_ty
                ));
                (ssa, ok_ty)
            }

            Expr::ErrorMapClosure { body, .. } => {
                Self::lower_expr(out, body, indent, ctx, expected_ty)
            }

            Expr::ArrayLit { elements, .. } => {
                let mut el_ssas = Vec::new();
                let mut el_tys = Vec::new();
                for el in elements {
                    let (s, t) = Self::lower_expr(out, el, indent, ctx, None);
                    el_ssas.push(s);
                    el_tys.push(t);
                }
                let elem_ty = el_tys.first().cloned().unwrap_or_else(|| "f32".to_string());
                let arr_ty = format!("memref<{}x{}>", elements.len(), elem_ty);
                let ssa = ctx.next_ssa();
                out.push_str(&format!(
                    "{}{} = \"rts.array_literal\"({}) : ({}) -> {}\n",
                    pad,
                    ssa,
                    el_ssas.join(", "),
                    el_tys.join(", "),
                    arr_ty
                ));
                (ssa, arr_ty)
            }
        }
    }

    fn ensure_index_type(
        out: &mut String,
        indent: usize,
        ctx: &mut MlirLoweringCtx,
        ssa: &str,
        ty: &str,
    ) -> String {
        if ty == "index" {
            return ssa.to_string();
        }
        let pad = "  ".repeat(indent);
        let cast_ssa = ctx.next_ssa();
        out.push_str(&format!(
            "{}{} = arith.index_cast {} : {} to index\n",
            pad, cast_ssa, ssa, ty
        ));
        cast_ssa
    }

    fn map_param_mlir_type(p: &FnParam) -> String {
        if let Some(cap) = &p.capability {
            match (&cap.kind, &cap.generic_arg) {
                (CapabilityKind::MutColumn, _) | (CapabilityKind::ReadColumn, _) => {
                    "memref<?xf32, strided<[1]>>".to_string()
                }
                (CapabilityKind::ScopedArena(_), elem_opt)
                | (CapabilityKind::ReadScopedArena(_), elem_opt) => {
                    let elem = match elem_opt {
                        Some(CapGenericArg::TypeName(t)) => t.clone(),
                        _ => "byte".to_string(),
                    };
                    format!("!rts.arena<\"{}\", \"{}\">", cap.domain_name, elem)
                }
                _ => format!("!rts.cap<\"{}\">", cap.domain_name),
            }
        } else {
            Self::map_mlir_type(&p.ty)
        }
    }

    pub fn map_mlir_type(ty: &TypeExpr) -> String {
        match ty {
            TypeExpr::Primitive(p) => match p {
                PrimitiveType::I8 | PrimitiveType::U8 => "i8".to_string(),
                PrimitiveType::I16 | PrimitiveType::U16 => "i16".to_string(),
                PrimitiveType::I32 | PrimitiveType::U32 | PrimitiveType::Fix32 => "i32".to_string(),
                PrimitiveType::I64 | PrimitiveType::U64 => "i64".to_string(),
                PrimitiveType::Usize => "index".to_string(),
                PrimitiveType::F32 => "f32".to_string(),
                PrimitiveType::F64 => "f64".to_string(),
                PrimitiveType::Bool => "i1".to_string(),
                PrimitiveType::Str => "!rts.str".to_string(),
            },
            TypeExpr::Math(m) => match m {
                MathType::Vec2 => "vector<2xf32>".to_string(),
                MathType::Vec3 => "vector<3xf32>".to_string(),
                MathType::Vec4 | MathType::Quat => "vector<4xf32>".to_string(),
                MathType::Mat3 => "memref<3x3xf32>".to_string(),
                MathType::Mat4 => "memref<4x4xf32>".to_string(),
            },
            TypeExpr::Array(inner, len) => {
                format!("memref<{}x{}>", len, Self::map_mlir_type(inner))
            }
            TypeExpr::Handle(inner) => {
                format!("!rts.handle<\"{}\">", Self::map_mlir_type(inner))
            }
            TypeExpr::Option(inner) => {
                format!("!rts.option<{}>", Self::map_mlir_type(inner))
            }
            TypeExpr::Result(ok, err) => {
                format!(
                    "!rts.result<{}, {}>",
                    Self::map_mlir_type(ok),
                    Self::map_mlir_type(err)
                )
            }
            TypeExpr::Capability(cap) => format!("!rts.cap<\"{}\">", cap.domain_name),
            TypeExpr::Named { name, .. } => format!("!rts.struct<\"{}\">", name),
        }
    }
}
