use crate::ast::*;
use std::collections::HashSet;

/// Gerador Direto de WebAssembly / WASI com *Fuel Metering* Determinístico (`rtsc v2.0.0-rts` — Fase 9 do Ciclo 2):
///   - `--target=wasi` / `--target=wat`: Emite módulos WebAssembly Text Format (`.wat`) com instrumentação automática
///     de combustível (`$__rts_fuel`) no prólogo de todas as funções e no *back-edge* de todos os loops (`while`/`for`),
///     garantindo tempo de execução determinístico $O(1)$ e *trap* imediato (`unreachable`) quando `$__rts_fuel < 0`.
///   - `--target=wasm` (ou `--target=wasi --bin`): Empacota diretamente um binário WebAssembly 1.0 (`.wasm`, magic `\0asm`,
///     versão `0x01`) com seções LEB128 válidas (Type, Function, Memory, Global, Export, Code).
pub struct WasiCodegen;

pub const WASM_MAGIC: [u8; 4] = [0x00, 0x61, 0x73, 0x6D]; // "\0asm"
pub const WASM_VERSION_1: [u8; 4] = [0x01, 0x00, 0x00, 0x00];
pub const DEFAULT_FUEL_LIMIT: u64 = 100_000;

impl WasiCodegen {
    // =========================================================================
    // 1. EMISSOR WEBASSEMBLY TEXT FORMAT (`.wat`) COM FUEL METERING
    // =========================================================================

    pub fn emit_wat(module: &Module, default_fuel: u64) -> String {
        let mut out = String::new();
        let mod_name = if module.path.is_empty() {
            "root".to_string()
        } else {
            module.path.join(".")
        };

        out.push_str(";; ==========================================================================\n");
        out.push_str(";; Generated by rtsc 2.0.0-rts --target=wasi (Deterministic Fuel-Metered Sandbox)\n");
        out.push_str(&format!(";; Source Module: {}\n", mod_name));
        out.push_str(&format!(";; Default Fuel Budget: {} ticks\n", default_fuel));
        out.push_str(";; Guarantees:\n");
        out.push_str(";;   1. Capability-Filtered WASI Imports (Zero Unlisted Host Syscalls)\n");
        out.push_str(";;   2. Automatic Fuel Metering on Function Prologues & Loop Back-Edges\n");
        out.push_str(";;   3. O(1) Deterministic Out-Of-Fuel Trap (`unreachable` when fuel < 0)\n");
        out.push_str(";;   4. Linear Arena Bump Allocator ($__rts_arena_cursor)\n");
        out.push_str(";; ==========================================================================\n\n");

        out.push_str("(module\n");

        // 1. Inspeciona quais capacidades WASI o módulo realmente utiliza para emitir apenas os imports autorizados
        let mut uses_stdio = false;
        let mut uses_clock = false;
        for item in &module.items {
            if let Item::Function(f) = item {
                for p in &f.params {
                    if let Some(cap) = &p.capability {
                        if cap.domain_name == "StdIO" {
                            uses_stdio = true;
                        }
                        if matches!(cap.domain_name.as_str(), "MonotonicClock" | "TimeStep")
                            || cap.kind == CapabilityKind::Clock
                        {
                            uses_clock = true;
                        }
                    }
                }
            }
        }

        if uses_stdio {
            out.push_str(
                "  (import \"wasi_snapshot_preview1\" \"fd_write\" (func $__wasi_fd_write (param i32 i32 i32 i32) (result i32)))\n",
            );
        }
        if uses_clock {
            out.push_str(
                "  (import \"wasi_snapshot_preview1\" \"clock_time_get\" (func $__wasi_clock_time_get (param i32 i64 i32) (result i32)))\n",
            );
        }

        // 2. Memória Linear Isolada (1 página = 64 KiB por padrão) e Globais de Combustível e Arena
        out.push_str("  (memory (export \"memory\") 1 16)\n");
        out.push_str(&format!(
            "  (global $__rts_fuel (mut i64) (i64.const {}))\n",
            default_fuel
        ));
        out.push_str("  (global $__rts_arena_cursor (mut i32) (i32.const 4096))\n\n");

        // 3. Funções Exportadas de Controle de Combustível e Arena ($O(1)$)
        out.push_str("  (func $rts_set_fuel (export \"rts_set_fuel\") (param $limit i64)\n");
        out.push_str("    (global.set $__rts_fuel (local.get $limit))\n");
        out.push_str("  )\n\n");

        out.push_str("  (func $rts_get_fuel (export \"rts_get_fuel\") (result i64)\n");
        out.push_str("    (global.get $__rts_fuel)\n");
        out.push_str("  )\n\n");

        out.push_str("  (func $rts_arena_reset (export \"rts_arena_reset\")\n");
        out.push_str("    (global.set $__rts_arena_cursor (i32.const 4096))\n");
        out.push_str("  )\n\n");

        // 4. Emissão das Funções do Módulo com Instrumentação de Fuel Metering
        let mut loop_counter = 0usize;
        for item in &module.items {
            if let Item::Function(f) = item {
                let export_attr = if f.is_pub || f.name == "main" {
                    format!(" (export \"{}\")", f.name)
                } else {
                    String::new()
                };

                let mut params_sig = Vec::new();
                let mut local_vars = HashSet::new();
                for p in &f.params {
                    if !p.is_cap {
                        let wat_ty = Self::map_wat_type(&p.ty);
                        params_sig.push(format!("(param ${} {})", p.name, wat_ty));
                        local_vars.insert((p.name.clone(), wat_ty));
                    }
                }

                let ret_wat = f.return_type.as_ref().map(Self::map_wat_type);
                let ret_sig = ret_wat
                    .as_ref()
                    .map(|t| format!(" (result {})", t))
                    .unwrap_or_default();

                // Coleta variáveis locais declaradas via `let` no corpo da função
                let mut declared_locals = Vec::new();
                Self::collect_wat_locals(&f.body, &mut declared_locals, &mut local_vars);

                out.push_str(&format!(
                    "  (func ${}{}{}{}\n",
                    f.name,
                    export_attr,
                    if params_sig.is_empty() {
                        String::new()
                    } else {
                        format!(" {}", params_sig.join(" "))
                    },
                    ret_sig
                ));

                for (l_name, l_ty) in &declared_locals {
                    out.push_str(&format!("    (local ${} {})\n", l_name, l_ty));
                }

                // Prólogo: Consumo determinístico de combustível de entrada da função
                let prologue_cost = (f.body.len().max(1) as u64) * 2;
                Self::emit_wat_fuel_check(&mut out, prologue_cost, 2);

                for stmt in &f.body {
                    Self::lower_wat_stmt(
                        &mut out,
                        stmt,
                        &ret_wat,
                        &mut loop_counter,
                        &local_vars,
                        2,
                    );
                }

                // Retorno padrão de segurança caso o final do bloco seja alcançável
                let ends_with_return = f
                    .body
                    .last()
                    .map(|s| matches!(s, Stmt::Return { .. }))
                    .unwrap_or(false);
                if !ends_with_return {
                    if let Some(rt) = &ret_wat {
                        out.push_str(&format!("    ({}.const 0)\n", rt));
                    }
                }

                out.push_str("  )\n\n");
            }
        }

        out.push_str(")\n");
        out
    }

    fn emit_wat_fuel_check(out: &mut String, cost: u64, indent: usize) {
        let pad = "  ".repeat(indent);
        out.push_str(&format!(
            "{};; [RTS-FUEL] Consume {} fuel ticks & trap if exhausted\n",
            pad, cost
        ));
        out.push_str(&format!(
            "{}(global.set $__rts_fuel (i64.sub (global.get $__rts_fuel) (i64.const {})))\n",
            pad, cost
        ));
        out.push_str(&format!(
            "{}(if (i64.lt_s (global.get $__rts_fuel) (i64.const 0))\n{}  (then (unreachable))\n{})\n",
            pad, pad, pad
        ));
    }

    fn collect_wat_locals(
        stmts: &[Stmt],
        out: &mut Vec<(String, String)>,
        seen: &mut HashSet<(String, String)>,
    ) {
        for stmt in stmts {
            match stmt {
                Stmt::Let {
                    name, ty, value, ..
                } => {
                    if matches!(ty, Some(TypeExpr::Capability(_))) {
                        continue;
                    }
                    let wat_ty = ty
                        .as_ref()
                        .map(Self::map_wat_type)
                        .unwrap_or_else(|| Self::infer_wat_expr_type(value));
                    if !seen.iter().any(|(n, _)| n == name) {
                        seen.insert((name.clone(), wat_ty.clone()));
                        out.push((name.clone(), wat_ty));
                    }
                }
                Stmt::If {
                    then_branch,
                    else_branch,
                    ..
                } => {
                    Self::collect_wat_locals(then_branch, out, seen);
                    if let Some(eb) = else_branch {
                        Self::collect_wat_locals(eb, out, seen);
                    }
                }
                Stmt::While { body, .. } => {
                    Self::collect_wat_locals(body, out, seen);
                }
                Stmt::ForRange { iterator, body, .. } => {
                    if !seen.iter().any(|(n, _)| n == iterator) {
                        seen.insert((iterator.clone(), "i32".to_string()));
                        out.push((iterator.clone(), "i32".to_string()));
                    }
                    Self::collect_wat_locals(body, out, seen);
                }
                Stmt::Match { arms, .. } => {
                    for arm in arms {
                        if let MatchPattern::Variant {
                            binding: Some(b), ..
                        } = &arm.pattern
                        {
                            if !seen.iter().any(|(n, _)| n == b) {
                                seen.insert((b.clone(), "f32".to_string()));
                                out.push((b.clone(), "f32".to_string()));
                            }
                        }
                        Self::collect_wat_locals(&arm.body, out, seen);
                    }
                }
                _ => {}
            }
        }
    }

    fn lower_wat_stmt(
        out: &mut String,
        stmt: &Stmt,
        fn_ret: &Option<String>,
        loop_counter: &mut usize,
        local_vars: &HashSet<(String, String)>,
        indent: usize,
    ) {
        let pad = "  ".repeat(indent);
        match stmt {
            Stmt::Let {
                name, ty, value, ..
            } => {
                if matches!(ty, Some(TypeExpr::Capability(_))) {
                    return;
                }
                let target_ty = local_vars
                    .iter()
                    .find(|(n, _)| n == name)
                    .map(|(_, t)| t.as_str())
                    .unwrap_or("f32");
                let val_s = Self::lower_wat_expr(value, Some(target_ty), local_vars);
                out.push_str(&format!("{}(local.set ${} {})\n", pad, name, val_s));
            }
            Stmt::Assign { target, value, .. } => {
                if let Expr::Ident(var_name, _) = target {
                    let target_ty = local_vars
                        .iter()
                        .find(|(n, _)| n == var_name)
                        .map(|(_, t)| t.as_str())
                        .unwrap_or("f32");
                    let val_s = Self::lower_wat_expr(value, Some(target_ty), local_vars);
                    out.push_str(&format!("{}(local.set ${} {})\n", pad, var_name, val_s));
                }
            }
            Stmt::If {
                condition,
                then_branch,
                else_branch,
                ..
            } => {
                let cond_s = Self::lower_wat_expr(condition, Some("i32"), local_vars);
                out.push_str(&format!("{}(if {}\n{}  (then\n", pad, cond_s, pad));
                for s in then_branch {
                    Self::lower_wat_stmt(out, s, fn_ret, loop_counter, local_vars, indent + 2);
                }
                out.push_str(&format!("{}  )\n", pad));
                if let Some(eb) = else_branch {
                    out.push_str(&format!("{}  (else\n", pad));
                    for s in eb {
                        Self::lower_wat_stmt(out, s, fn_ret, loop_counter, local_vars, indent + 2);
                    }
                    out.push_str(&format!("{}  )\n", pad));
                }
                out.push_str(&format!("{})\n", pad));
            }
            Stmt::While {
                condition, body, ..
            } => {
                let id = *loop_counter;
                *loop_counter += 1;
                let blk_lbl = format!("$while_exit_{}", id);
                let lp_lbl = format!("$while_loop_{}", id);
                let cond_s = Self::lower_wat_expr(condition, Some("i32"), local_vars);

                out.push_str(&format!("{}(block {}\n", pad, blk_lbl));
                out.push_str(&format!("{}  (loop {}\n", pad, lp_lbl));
                out.push_str(&format!(
                    "{}    (br_if {} (i32.eqz {}))\n",
                    pad, blk_lbl, cond_s
                ));

                // Instrumentação de Fuel Metering no back-edge do loop `while`
                let loop_cost = (body.len().max(1) as u64) * 3;
                Self::emit_wat_fuel_check(out, loop_cost, indent + 2);

                for s in body {
                    Self::lower_wat_stmt(out, s, fn_ret, loop_counter, local_vars, indent + 2);
                }
                out.push_str(&format!("{}    (br {})\n", pad, lp_lbl));
                out.push_str(&format!("{}  )\n", pad));
                out.push_str(&format!("{})\n", pad));
            }
            Stmt::ForRange {
                iterator,
                start,
                end,
                body,
                ..
            } => {
                let id = *loop_counter;
                *loop_counter += 1;
                let blk_lbl = format!("$for_exit_{}", id);
                let lp_lbl = format!("$for_loop_{}", id);
                let start_s = Self::lower_wat_expr(start, Some("i32"), local_vars);
                let end_s = Self::lower_wat_expr(end, Some("i32"), local_vars);

                out.push_str(&format!("{}(local.set ${} {})\n", pad, iterator, start_s));
                out.push_str(&format!("{}(block {}\n", pad, blk_lbl));
                out.push_str(&format!("{}  (loop {}\n", pad, lp_lbl));
                out.push_str(&format!(
                    "{}    (br_if {} (i32.ge_u (local.get ${}) {}))\n",
                    pad, blk_lbl, iterator, end_s
                ));

                // Instrumentação de Fuel Metering no back-edge do loop `for`
                let loop_cost = (body.len().max(1) as u64) * 3;
                Self::emit_wat_fuel_check(out, loop_cost, indent + 2);

                for s in body {
                    Self::lower_wat_stmt(out, s, fn_ret, loop_counter, local_vars, indent + 2);
                }
                out.push_str(&format!(
                    "{}    (local.set ${} (i32.add (local.get ${}) (i32.const 1)))\n",
                    pad, iterator, iterator
                ));
                out.push_str(&format!("{}    (br {})\n", pad, lp_lbl));
                out.push_str(&format!("{}  )\n", pad));
                out.push_str(&format!("{})\n", pad));
            }
            Stmt::Break { .. } => {
                let cur_id = loop_counter.saturating_sub(1);
                out.push_str(&format!("{}(br $while_exit_{})\n", pad, cur_id));
            }
            Stmt::Continue { .. } => {
                let cur_id = loop_counter.saturating_sub(1);
                out.push_str(&format!("{}(br $while_loop_{})\n", pad, cur_id));
            }
            Stmt::Return { value, .. } => {
                if let Some(v) = value {
                    let ret_ty = fn_ret.as_deref().unwrap_or("i32");
                    let vs = Self::lower_wat_expr(v, Some(ret_ty), local_vars);
                    out.push_str(&format!("{}(return {})\n", pad, vs));
                } else if let Some(rt) = fn_ret {
                    out.push_str(&format!("{}(return ({}.const 0))\n", pad, rt));
                } else {
                    out.push_str(&format!("{}(return)\n", pad));
                }
            }
            Stmt::ExprStmt { expr, .. } => {
                let _ = Self::lower_wat_expr(expr, None, local_vars);
            }
            _ => {}
        }
    }

    fn lower_wat_expr(
        expr: &Expr,
        expected_ty: Option<&str>,
        local_vars: &HashSet<(String, String)>,
    ) -> String {
        match expr {
            Expr::IntLit(v, _) => {
                let ty = match expected_ty {
                    Some("i64") => "i64",
                    Some("f32") => return format!("(f32.const {}.0)", v),
                    Some("f64") => return format!("(f64.const {}.0)", v),
                    _ => "i32",
                };
                format!("({}.const {})", ty, v)
            }
            Expr::FloatLit(v, _) => {
                let ty = match expected_ty {
                    Some("f64") => "f64",
                    _ => "f32",
                };
                if v.fract() == 0.0 {
                    format!("({}.const {:.1})", ty, v)
                } else {
                    format!("({}.const {})", ty, v)
                }
            }
            Expr::BoolLit(b, _) => {
                format!("(i32.const {})", if *b { 1 } else { 0 })
            }
            Expr::Ident(name, _) => {
                format!("(local.get ${})", name)
            }
            Expr::Unary { op, expr: inner, .. } => {
                let ty = expected_ty.unwrap_or("f32");
                let in_s = Self::lower_wat_expr(inner, Some(ty), local_vars);
                match op {
                    UnaryOp::Neg => {
                        if ty.starts_with('f') {
                            format!("({}.neg {})", ty, in_s)
                        } else {
                            format!("({}.sub ({}.const 0) {})", ty, ty, in_s)
                        }
                    }
                    UnaryOp::Not => format!("(i32.eqz {})", in_s),
                }
            }
            Expr::Binary {
                left, op, right, ..
            } => {
                let operand_ty = Self::infer_wat_expr_type(left);
                let l = Self::lower_wat_expr(left, Some(&operand_ty), local_vars);
                let r = Self::lower_wat_expr(right, Some(&operand_ty), local_vars);
                let is_float = operand_ty.starts_with('f');
                let wat_op = match op {
                    BinaryOp::Add => format!("{}.add", operand_ty),
                    BinaryOp::Sub => format!("{}.sub", operand_ty),
                    BinaryOp::Mul => format!("{}.mul", operand_ty),
                    BinaryOp::Div => {
                        if is_float {
                            format!("{}.div", operand_ty)
                        } else {
                            format!("{}.div_s", operand_ty)
                        }
                    }
                    BinaryOp::Eq => format!("{}.eq", operand_ty),
                    BinaryOp::NotEq => format!("{}.ne", operand_ty),
                    BinaryOp::Lt => {
                        if is_float {
                            format!("{}.lt", operand_ty)
                        } else {
                            format!("{}.lt_s", operand_ty)
                        }
                    }
                    BinaryOp::LtEq => {
                        if is_float {
                            format!("{}.le", operand_ty)
                        } else {
                            format!("{}.le_s", operand_ty)
                        }
                    }
                    BinaryOp::Gt => {
                        if is_float {
                            format!("{}.gt", operand_ty)
                        } else {
                            format!("{}.gt_s", operand_ty)
                        }
                    }
                    BinaryOp::GtEq => {
                        if is_float {
                            format!("{}.ge", operand_ty)
                        } else {
                            format!("{}.ge_s", operand_ty)
                        }
                    }
                    BinaryOp::And => "i32.and".to_string(),
                    BinaryOp::Or => "i32.or".to_string(),
                };
                format!("({} {} {})", wat_op, l, r)
            }
            Expr::StaticCall {
                namespace,
                func,
                args,
                ..
            } => {
                let arg_s: Vec<String> = args
                    .iter()
                    .map(|a| Self::lower_wat_expr(a, Some("f32"), local_vars))
                    .collect();
                if namespace == "math" {
                    match func.as_str() {
                        "sqrt" | "abs" | "floor" | "ceil" if arg_s.len() == 1 => {
                            return format!("(f32.{} {})", func, arg_s[0]);
                        }
                        "lerp" if arg_s.len() == 3 => {
                            return format!(
                                "(f32.add {} (f32.mul (f32.sub {} {}) {}))",
                                arg_s[0], arg_s[1], arg_s[0], arg_s[2]
                            );
                        }
                        _ => {}
                    }
                }
                if arg_s.is_empty() {
                    format!("(call ${})", func)
                } else {
                    format!("(call ${} {})", func, arg_s.join(" "))
                }
            }
            Expr::Cast {
                expr: inner,
                target_type,
                ..
            } => {
                let dst_ty = Self::map_wat_type(target_type);
                Self::lower_wat_expr(inner, Some(&dst_ty), local_vars)
            }
            _ => {
                let ty = expected_ty.unwrap_or("i32");
                if ty.starts_with('f') {
                    format!("({}.const 0.0)", ty)
                } else {
                    format!("({}.const 0)", ty)
                }
            }
        }
    }

    fn infer_wat_expr_type(expr: &Expr) -> String {
        match expr {
            Expr::FloatLit(_, _) => "f32".to_string(),
            Expr::IntLit(_, _) | Expr::BoolLit(_, _) => "i32".to_string(),
            Expr::Binary { left, .. } => Self::infer_wat_expr_type(left),
            Expr::Cast { target_type, .. } => Self::map_wat_type(target_type),
            _ => "f32".to_string(),
        }
    }

    pub fn map_wat_type(ty: &TypeExpr) -> String {
        match ty {
            TypeExpr::Primitive(PrimitiveType::I64 | PrimitiveType::U64) => "i64".to_string(),
            TypeExpr::Primitive(PrimitiveType::F32) => "f32".to_string(),
            TypeExpr::Primitive(PrimitiveType::F64) => "f64".to_string(),
            _ => "i32".to_string(),
        }
    }

    // =========================================================================
    // 2. EMPACOTADOR BINÁRIO WEBASSEMBLY 1.0 (`.wasm`, MAGIC `\0asm`)
    // =========================================================================

    pub fn emit_wasm_binary(module: &Module, default_fuel: u64) -> Vec<u8> {
        let mut wasm = Vec::with_capacity(512);

        // Cabeçalho WebAssembly 1.0 (8 bytes: "\0asm" + version 1)
        wasm.extend_from_slice(&WASM_MAGIC);
        wasm.extend_from_slice(&WASM_VERSION_1);

        // Coleta as funções reais definidas no módulo do usuário
        let mut user_funcs: Vec<&FnDecl> = Vec::new();
        let mut fn_index_map: std::collections::HashMap<String, (u32, u8)> =
            std::collections::HashMap::new();
        for item in &module.items {
            if let Item::Function(f) = item {
                let fn_idx = (3 + user_funcs.len()) as u32;
                let ret_vt = f
                    .return_type
                    .as_ref()
                    .map(Self::wasm_valtype_byte)
                    .unwrap_or(0x7F);
                fn_index_map.insert(f.name.clone(), (fn_idx, ret_vt));
                user_funcs.push(f);
            }
        }

        // --- Section 1: Type Section (ID = 1) ---
        // Type 0: (param i64) -> ()          [rts_set_fuel]
        // Type 1: () -> (result i64)         [rts_get_fuel]
        // Type 2: () -> ()                   [rts_arena_reset]
        // Type 3+i: assinatura real (params + result) de cada função do usuário
        let mut type_sec = Vec::new();
        let total_types = 3 + user_funcs.len();
        Self::push_u32_leb128(&mut type_sec, total_types as u32);
        // Type 0: func (i64) -> ()
        type_sec.extend_from_slice(&[0x60, 0x01, 0x7E, 0x00]);
        // Type 1: func () -> (i64)
        type_sec.extend_from_slice(&[0x60, 0x00, 0x01, 0x7E]);
        // Type 2: func () -> ()
        type_sec.extend_from_slice(&[0x60, 0x00, 0x00]);
        // Types 3..3+N: assinaturas reais das funções do usuário
        for f in &user_funcs {
            type_sec.push(0x60); // func type tag
            let non_cap_params: Vec<&FnParam> = f.params.iter().filter(|p| !p.is_cap).collect();
            Self::push_u32_leb128(&mut type_sec, non_cap_params.len() as u32);
            for p in &non_cap_params {
                type_sec.push(Self::wasm_valtype_byte(&p.ty));
            }
            match &f.return_type {
                None => {
                    type_sec.push(0x00); // 0 results
                }
                Some(ret_ty) => {
                    type_sec.push(0x01); // 1 result
                    type_sec.push(Self::wasm_valtype_byte(ret_ty));
                }
            }
        }
        Self::emit_wasm_section(&mut wasm, 1, &type_sec);

        // --- Section 3: Function Section (ID = 3) ---
        let total_funcs = 3 + user_funcs.len();
        let mut func_sec = Vec::new();
        Self::push_u32_leb128(&mut func_sec, total_funcs as u32);
        func_sec.push(0); // func 0 -> type 0 (rts_set_fuel)
        func_sec.push(1); // func 1 -> type 1 (rts_get_fuel)
        func_sec.push(2); // func 2 -> type 2 (rts_arena_reset)
        for idx in 0..user_funcs.len() {
            Self::push_u32_leb128(&mut func_sec, (3 + idx) as u32);
        }
        Self::emit_wasm_section(&mut wasm, 3, &func_sec);

        // --- Section 5: Memory Section (ID = 5) ---
        // 1 memory with min=1 page (64 KiB), max=16 pages (1 MiB)
        let mem_sec = vec![0x01, 0x01, 0x01, 0x10];
        Self::emit_wasm_section(&mut wasm, 5, &mem_sec);

        // --- Section 6: Global Section (ID = 6) ---
        // Global 0: $__rts_fuel (i64, mut=1) = i64.const <default_fuel>
        // Global 1: $__rts_arena_cursor (i32, mut=1) = i32.const 4096
        let mut glob_sec = Vec::new();
        Self::push_u32_leb128(&mut glob_sec, 2);
        // Global 0 ($__rts_fuel)
        glob_sec.push(0x7E); // i64
        glob_sec.push(0x01); // mut
        glob_sec.push(0x42); // i64.const
        Self::push_i64_leb128(&mut glob_sec, default_fuel as i64);
        glob_sec.push(0x0B); // end
        // Global 1 ($__rts_arena_cursor)
        glob_sec.push(0x7F); // i32
        glob_sec.push(0x01); // mut
        glob_sec.push(0x41); // i32.const
        Self::push_i64_leb128(&mut glob_sec, 4096);
        glob_sec.push(0x0B); // end
        Self::emit_wasm_section(&mut wasm, 6, &glob_sec);

        // --- Section 7: Export Section (ID = 7) ---
        let exported_user_funcs: Vec<(usize, &FnDecl)> = user_funcs
            .iter()
            .enumerate()
            .filter(|(_, f)| f.is_pub || f.name == "main")
            .map(|(i, f)| (i, *f))
            .collect();
        let mut exp_sec = Vec::new();
        let total_exports = 4 + exported_user_funcs.len();
        Self::push_u32_leb128(&mut exp_sec, total_exports as u32);
        Self::push_wasm_export(&mut exp_sec, "memory", 0x02, 0);
        Self::push_wasm_export(&mut exp_sec, "rts_set_fuel", 0x00, 0);
        Self::push_wasm_export(&mut exp_sec, "rts_get_fuel", 0x00, 1);
        Self::push_wasm_export(&mut exp_sec, "rts_arena_reset", 0x00, 2);
        for (idx, f) in &exported_user_funcs {
            Self::push_wasm_export(&mut exp_sec, &f.name, 0x00, (3 + *idx) as u32);
        }
        Self::emit_wasm_section(&mut wasm, 7, &exp_sec);

        // --- Section 10: Code Section (ID = 10) ---
        let mut code_sec = Vec::new();
        Self::push_u32_leb128(&mut code_sec, total_funcs as u32);

        // Body 0: rts_set_fuel(limit: i64) -> local.get 0, global.set 0, end
        let body0 = vec![0x00, 0x20, 0x00, 0x24, 0x00, 0x0B];
        Self::push_u32_leb128(&mut code_sec, body0.len() as u32);
        code_sec.extend_from_slice(&body0);

        // Body 1: rts_get_fuel() -> global.get 0, end
        let body1 = vec![0x00, 0x23, 0x00, 0x0B];
        Self::push_u32_leb128(&mut code_sec, body1.len() as u32);
        code_sec.extend_from_slice(&body1);

        // Body 2: rts_arena_reset() -> i32.const 4096, global.set 1, end
        let mut body2 = vec![0x00, 0x41];
        Self::push_i64_leb128(&mut body2, 4096);
        body2.extend_from_slice(&[0x24, 0x01, 0x0B]);
        Self::push_u32_leb128(&mut code_sec, body2.len() as u32);
        code_sec.extend_from_slice(&body2);

        // Bodies 3..3+N: Lowering real da AST de cada função do usuário para bytecode WebAssembly 1.0
        for f in &user_funcs {
            let user_body = Self::compile_wasm_function_body(f, &fn_index_map);
            Self::push_u32_leb128(&mut code_sec, user_body.len() as u32);
            code_sec.extend_from_slice(&user_body);
        }

        Self::emit_wasm_section(&mut wasm, 10, &code_sec);

        wasm
    }

    fn wasm_valtype_byte(ty: &TypeExpr) -> u8 {
        match ty {
            TypeExpr::Primitive(PrimitiveType::F32) => 0x7D, // f32
            TypeExpr::Primitive(PrimitiveType::F64) => 0x7C, // f64
            TypeExpr::Primitive(PrimitiveType::I64 | PrimitiveType::U64) => 0x7E, // i64
            _ => 0x7F,                                       // i32
        }
    }

    fn compile_wasm_function_body(
        func: &FnDecl,
        fn_index_map: &std::collections::HashMap<String, (u32, u8)>,
    ) -> Vec<u8> {
        let mut local_map: std::collections::HashMap<String, (u32, u8)> =
            std::collections::HashMap::new();
        let mut next_local_idx: u32 = 0;

        for p in func.params.iter().filter(|p| !p.is_cap) {
            let vt = Self::wasm_valtype_byte(&p.ty);
            local_map.insert(p.name.clone(), (next_local_idx, vt));
            next_local_idx += 1;
        }

        let mut declared_locals: Vec<u8> = Vec::new();
        Self::collect_wasm_locals(
            &func.body,
            &mut local_map,
            &mut declared_locals,
            &mut next_local_idx,
            fn_index_map,
        );

        let mut body = Vec::new();
        // Declaração das variáveis locais da função (cada entrada: count=1, valtype)
        Self::push_u32_leb128(&mut body, declared_locals.len() as u32);
        for vt in &declared_locals {
            body.push(0x01);
            body.push(*vt);
        }

        // Instrumentação de prólogo: consome 10 unidades de combustível
        Self::emit_wasm_fuel_check(&mut body, 10);

        let ret_vt_opt = func.return_type.as_ref().map(Self::wasm_valtype_byte);

        for stmt in &func.body {
            Self::emit_wasm_stmt(
                stmt,
                ret_vt_opt,
                &local_map,
                fn_index_map,
                None,
                &mut body,
            );
        }

        // Retorno fallback determinístico ao final do bloco da função caso o fluxo alcance o final
        if let Some(ret_vt) = ret_vt_opt {
            match ret_vt {
                0x7D => {
                    body.push(0x43); // f32.const 0.0
                    body.extend_from_slice(&0.0f32.to_le_bytes());
                }
                0x7C => {
                    body.push(0x44); // f64.const 0.0
                    body.extend_from_slice(&0.0f64.to_le_bytes());
                }
                0x7E => {
                    body.push(0x42); // i64.const 0
                    Self::push_i64_leb128(&mut body, 0);
                }
                _ => {
                    body.push(0x41); // i32.const 0
                    Self::push_i64_leb128(&mut body, 0);
                }
            }
        }

        body.push(0x0B); // end function
        body
    }

    fn collect_wasm_locals(
        stmts: &[Stmt],
        local_map: &mut std::collections::HashMap<String, (u32, u8)>,
        declared_locals: &mut Vec<u8>,
        next_local_idx: &mut u32,
        fn_index_map: &std::collections::HashMap<String, (u32, u8)>,
    ) {
        for stmt in stmts {
            match stmt {
                Stmt::Let {
                    name, ty, value, ..
                } => {
                    if !local_map.contains_key(name) {
                        let vt = ty
                            .as_ref()
                            .map(Self::wasm_valtype_byte)
                            .or_else(|| Self::infer_wasm_valtype(value, local_map, fn_index_map))
                            .unwrap_or(0x7F);
                        local_map.insert(name.clone(), (*next_local_idx, vt));
                        declared_locals.push(vt);
                        *next_local_idx += 1;
                    }
                }
                Stmt::If {
                    then_branch,
                    else_branch,
                    ..
                } => {
                    Self::collect_wasm_locals(
                        then_branch,
                        local_map,
                        declared_locals,
                        next_local_idx,
                        fn_index_map,
                    );
                    if let Some(else_stmts) = else_branch {
                        Self::collect_wasm_locals(
                            else_stmts,
                            local_map,
                            declared_locals,
                            next_local_idx,
                            fn_index_map,
                        );
                    }
                }
                Stmt::While { body, .. } => {
                    Self::collect_wasm_locals(
                        body,
                        local_map,
                        declared_locals,
                        next_local_idx,
                        fn_index_map,
                    );
                }
                Stmt::ForRange { iterator, body, .. } => {
                    if !local_map.contains_key(iterator) {
                        local_map.insert(iterator.clone(), (*next_local_idx, 0x7F));
                        declared_locals.push(0x7F);
                        *next_local_idx += 1;
                    }
                    Self::collect_wasm_locals(
                        body,
                        local_map,
                        declared_locals,
                        next_local_idx,
                        fn_index_map,
                    );
                }
                Stmt::Match { arms, .. } => {
                    for arm in arms {
                        Self::collect_wasm_locals(
                            &arm.body,
                            local_map,
                            declared_locals,
                            next_local_idx,
                            fn_index_map,
                        );
                    }
                }
                _ => {}
            }
        }
    }

    fn infer_wasm_valtype(
        expr: &Expr,
        local_map: &std::collections::HashMap<String, (u32, u8)>,
        fn_index_map: &std::collections::HashMap<String, (u32, u8)>,
    ) -> Option<u8> {
        match expr {
            Expr::IntLit(_, _) | Expr::BoolLit(_, _) => Some(0x7F),
            Expr::FloatLit(_, _) => Some(0x7D),
            Expr::Ident(name, _) => local_map.get(name).map(|(_, vt)| *vt),
            Expr::Unary { expr: inner, .. } => {
                Self::infer_wasm_valtype(inner, local_map, fn_index_map)
            }
            Expr::Binary { left, op, right, .. } => match op {
                BinaryOp::Eq
                | BinaryOp::NotEq
                | BinaryOp::Lt
                | BinaryOp::Gt
                | BinaryOp::LtEq
                | BinaryOp::GtEq
                | BinaryOp::And
                | BinaryOp::Or => Some(0x7F),
                _ => {
                    let lt = Self::infer_wasm_valtype(left, local_map, fn_index_map);
                    let rt = Self::infer_wasm_valtype(right, local_map, fn_index_map);
                    if lt == Some(0x7C) || rt == Some(0x7C) {
                        Some(0x7C)
                    } else if lt == Some(0x7D) || rt == Some(0x7D) {
                        Some(0x7D)
                    } else if lt == Some(0x7E) || rt == Some(0x7E) {
                        Some(0x7E)
                    } else {
                        lt.or(rt).or(Some(0x7F))
                    }
                }
            },
            Expr::Cast { target_type, .. } => Some(Self::wasm_valtype_byte(target_type)),
            Expr::StaticCall { func, .. } => fn_index_map.get(func).map(|(_, vt)| *vt),
            _ => Some(0x7F),
        }
    }

    fn emit_wasm_fuel_check(body: &mut Vec<u8>, cost: i64) {
        body.extend_from_slice(&[0x23, 0x00]); // global.get 0 ($__rts_fuel)
        body.push(0x42); // i64.const <cost>
        Self::push_i64_leb128(body, cost);
        body.push(0x7D); // i64.sub
        body.extend_from_slice(&[0x24, 0x00]); // global.set 0 ($__rts_fuel)
        body.extend_from_slice(&[0x23, 0x00]); // global.get 0 ($__rts_fuel)
        body.extend_from_slice(&[0x42, 0x00]); // i64.const 0
        body.push(0x53); // i64.lt_s
        body.extend_from_slice(&[0x04, 0x40]); // if (void)
        body.push(0x00); // unreachable (Deterministic Out-Of-Fuel Trap)
        body.push(0x0B); // end if
    }

    fn emit_wasm_stmt(
        stmt: &Stmt,
        ret_vt_opt: Option<u8>,
        local_map: &std::collections::HashMap<String, (u32, u8)>,
        fn_index_map: &std::collections::HashMap<String, (u32, u8)>,
        loop_depth: Option<u32>,
        body: &mut Vec<u8>,
    ) {
        match stmt {
            Stmt::Let { name, value, .. } => {
                if let Some(&(local_idx, expected_vt)) = local_map.get(name) {
                    Self::emit_wasm_expr(value, expected_vt, local_map, fn_index_map, body);
                    body.push(0x21); // local.set
                    Self::push_u32_leb128(body, local_idx);
                }
            }
            Stmt::Assign { target, value, .. } => {
                if let Expr::Ident(name, _) = target {
                    if let Some(&(local_idx, expected_vt)) = local_map.get(name) {
                        Self::emit_wasm_expr(value, expected_vt, local_map, fn_index_map, body);
                        body.push(0x21); // local.set
                        Self::push_u32_leb128(body, local_idx);
                    }
                }
            }
            Stmt::If {
                condition,
                then_branch,
                else_branch,
                ..
            } => {
                Self::emit_wasm_expr(condition, 0x7F, local_map, fn_index_map, body);
                body.extend_from_slice(&[0x04, 0x40]); // if (void)
                let nested_depth = loop_depth.map(|d| d + 1);
                for s in then_branch {
                    Self::emit_wasm_stmt(
                        s,
                        ret_vt_opt,
                        local_map,
                        fn_index_map,
                        nested_depth,
                        body,
                    );
                }
                if let Some(else_stmts) = else_branch {
                    body.push(0x05); // else
                    for s in else_stmts {
                        Self::emit_wasm_stmt(
                            s,
                            ret_vt_opt,
                            local_map,
                            fn_index_map,
                            nested_depth,
                            body,
                        );
                    }
                }
                body.push(0x0B); // end if
            }
            Stmt::While {
                condition,
                body: loop_body,
                ..
            } => {
                body.extend_from_slice(&[0x02, 0x40]); // block $exit (void)
                body.extend_from_slice(&[0x03, 0x40]); // loop $cont (void)
                Self::emit_wasm_expr(condition, 0x7F, local_map, fn_index_map, body);
                body.push(0x45); // i32.eqz
                body.extend_from_slice(&[0x0D, 0x01]); // br_if 1 ($exit)
                Self::emit_wasm_fuel_check(body, 15);
                for s in loop_body {
                    Self::emit_wasm_stmt(s, ret_vt_opt, local_map, fn_index_map, Some(0), body);
                }
                body.extend_from_slice(&[0x0C, 0x00]); // br 0 ($cont)
                body.push(0x0B); // end loop
                body.push(0x0B); // end block
            }
            Stmt::ForRange {
                iterator,
                start,
                end,
                body: loop_body,
                ..
            } => {
                if let Some(&(iter_idx, _)) = local_map.get(iterator) {
                    Self::emit_wasm_expr(start, 0x7F, local_map, fn_index_map, body);
                    body.push(0x21); // local.set iter_idx
                    Self::push_u32_leb128(body, iter_idx);

                    body.extend_from_slice(&[0x02, 0x40]); // block $exit (void)
                    body.extend_from_slice(&[0x03, 0x40]); // loop $cont (void)
                    body.push(0x20); // local.get iter_idx
                    Self::push_u32_leb128(body, iter_idx);
                    Self::emit_wasm_expr(end, 0x7F, local_map, fn_index_map, body);
                    body.push(0x4E); // i32.ge_s
                    body.extend_from_slice(&[0x0D, 0x01]); // br_if 1 ($exit)
                    Self::emit_wasm_fuel_check(body, 15);
                    for s in loop_body {
                        Self::emit_wasm_stmt(
                            s,
                            ret_vt_opt,
                            local_map,
                            fn_index_map,
                            Some(0),
                            body,
                        );
                    }
                    body.push(0x20); // local.get iter_idx
                    Self::push_u32_leb128(body, iter_idx);
                    body.extend_from_slice(&[0x41, 0x01, 0x6A]); // i32.const 1, i32.add
                    body.push(0x21); // local.set iter_idx
                    Self::push_u32_leb128(body, iter_idx);
                    body.extend_from_slice(&[0x0C, 0x00]); // br 0 ($cont)
                    body.push(0x0B); // end loop
                    body.push(0x0B); // end block
                }
            }
            Stmt::Break { .. } => {
                if let Some(depth) = loop_depth {
                    body.push(0x0C); // br ($exit = depth + 1)
                    Self::push_u32_leb128(body, depth + 1);
                }
            }
            Stmt::Continue { .. } => {
                if let Some(depth) = loop_depth {
                    body.push(0x0C); // br ($cont = depth)
                    Self::push_u32_leb128(body, depth);
                }
            }
            Stmt::Return { value, .. } => {
                if let Some(expr) = value {
                    let expected_vt = ret_vt_opt.unwrap_or(0x7F);
                    Self::emit_wasm_expr(expr, expected_vt, local_map, fn_index_map, body);
                }
                body.push(0x0F); // return
            }
            Stmt::ExprStmt { expr, .. } => {
                let vt =
                    Self::infer_wasm_valtype(expr, local_map, fn_index_map).unwrap_or(0x7F);
                Self::emit_wasm_expr(expr, vt, local_map, fn_index_map, body);
                body.push(0x1A); // drop
            }
            Stmt::Match { arms, .. } => {
                for arm in arms {
                    for s in &arm.body {
                        Self::emit_wasm_stmt(
                            s,
                            ret_vt_opt,
                            local_map,
                            fn_index_map,
                            loop_depth,
                            body,
                        );
                    }
                }
            }
        }
    }

    fn emit_wasm_expr(
        expr: &Expr,
        expected_vt: u8,
        local_map: &std::collections::HashMap<String, (u32, u8)>,
        fn_index_map: &std::collections::HashMap<String, (u32, u8)>,
        body: &mut Vec<u8>,
    ) {
        match expr {
            Expr::IntLit(v, _) => match expected_vt {
                0x7D => {
                    body.push(0x43); // f32.const
                    body.extend_from_slice(&(*v as f32).to_le_bytes());
                }
                0x7C => {
                    body.push(0x44); // f64.const
                    body.extend_from_slice(&(*v as f64).to_le_bytes());
                }
                0x7E => {
                    body.push(0x42); // i64.const
                    Self::push_i64_leb128(body, *v as i64);
                }
                _ => {
                    body.push(0x41); // i32.const
                    Self::push_i64_leb128(body, *v as i64);
                }
            },
            Expr::FloatLit(v, _) => match expected_vt {
                0x7C => {
                    body.push(0x44); // f64.const
                    body.extend_from_slice(&v.to_le_bytes());
                }
                _ => {
                    body.push(0x43); // f32.const
                    body.extend_from_slice(&(*v as f32).to_le_bytes());
                }
            },
            Expr::BoolLit(b, _) => {
                body.push(0x41); // i32.const
                Self::push_i64_leb128(body, if *b { 1 } else { 0 });
            }
            Expr::Ident(name, _) => {
                if let Some(&(local_idx, local_vt)) = local_map.get(name) {
                    body.push(0x20); // local.get
                    Self::push_u32_leb128(body, local_idx);
                    Self::emit_wasm_valtype_coercion(local_vt, expected_vt, body);
                } else {
                    body.extend_from_slice(&[0x41, 0x00]); // fallback i32.const 0
                    Self::emit_wasm_valtype_coercion(0x7F, expected_vt, body);
                }
            }
            Expr::Unary {
                op, expr: inner, ..
            } => {
                let inner_vt = Self::infer_wasm_valtype(inner, local_map, fn_index_map)
                    .unwrap_or(expected_vt);
                match op {
                    UnaryOp::Neg => match inner_vt {
                        0x7D => {
                            Self::emit_wasm_expr(inner, 0x7D, local_map, fn_index_map, body);
                            body.push(0x8C); // f32.neg
                        }
                        0x7C => {
                            Self::emit_wasm_expr(inner, 0x7C, local_map, fn_index_map, body);
                            body.push(0x9A); // f64.neg
                        }
                        0x7E => {
                            body.extend_from_slice(&[0x42, 0x00]); // i64.const 0
                            Self::emit_wasm_expr(inner, 0x7E, local_map, fn_index_map, body);
                            body.push(0x7D); // i64.sub
                        }
                        _ => {
                            body.extend_from_slice(&[0x41, 0x00]); // i32.const 0
                            Self::emit_wasm_expr(inner, 0x7F, local_map, fn_index_map, body);
                            body.push(0x6B); // i32.sub
                        }
                    },
                    UnaryOp::Not => {
                        Self::emit_wasm_expr(inner, 0x7F, local_map, fn_index_map, body);
                        body.push(0x45); // i32.eqz
                    }
                }
            }
            Expr::Binary {
                left, op, right, ..
            } => {
                let lt = Self::infer_wasm_valtype(left, local_map, fn_index_map);
                let rt = Self::infer_wasm_valtype(right, local_map, fn_index_map);
                let op_vt = if lt == Some(0x7C) || rt == Some(0x7C) {
                    0x7C
                } else if lt == Some(0x7D) || rt == Some(0x7D) {
                    0x7D
                } else if lt == Some(0x7E) || rt == Some(0x7E) {
                    0x7E
                } else {
                    0x7F
                };

                Self::emit_wasm_expr(left, op_vt, local_map, fn_index_map, body);
                Self::emit_wasm_expr(right, op_vt, local_map, fn_index_map, body);

                let opcode = match op_vt {
                    0x7D => match op {
                        BinaryOp::Add => 0x92,   // f32.add
                        BinaryOp::Sub => 0x93,   // f32.sub
                        BinaryOp::Mul => 0x94,   // f32.mul
                        BinaryOp::Div => 0x95,   // f32.div
                        BinaryOp::Eq => 0x5B,    // f32.eq
                        BinaryOp::NotEq => 0x5C, // f32.ne
                        BinaryOp::Lt => 0x5D,    // f32.lt
                        BinaryOp::Gt => 0x5E,    // f32.gt
                        BinaryOp::LtEq => 0x5F,  // f32.le
                        BinaryOp::GtEq => 0x60,  // f32.ge
                        _ => 0x92,
                    },
                    0x7C => match op {
                        BinaryOp::Add => 0xA0,   // f64.add
                        BinaryOp::Sub => 0xA1,   // f64.sub
                        BinaryOp::Mul => 0xA2,   // f64.mul
                        BinaryOp::Div => 0xA3,   // f64.div
                        BinaryOp::Eq => 0x61,    // f64.eq
                        BinaryOp::NotEq => 0x62, // f64.ne
                        BinaryOp::Lt => 0x63,    // f64.lt
                        BinaryOp::Gt => 0x64,    // f64.gt
                        BinaryOp::LtEq => 0x65,  // f64.le
                        BinaryOp::GtEq => 0x66,  // f64.ge
                        _ => 0xA0,
                    },
                    0x7E => match op {
                        BinaryOp::Add => 0x7C,   // i64.add
                        BinaryOp::Sub => 0x7D,   // i64.sub
                        BinaryOp::Mul => 0x7E,   // i64.mul
                        BinaryOp::Div => 0x7F,   // i64.div_s
                        BinaryOp::Eq => 0x51,    // i64.eq
                        BinaryOp::NotEq => 0x52, // i64.ne
                        BinaryOp::Lt => 0x53,    // i64.lt_s
                        BinaryOp::Gt => 0x55,    // i64.gt_s
                        BinaryOp::LtEq => 0x57,  // i64.le_s
                        BinaryOp::GtEq => 0x59,  // i64.ge_s
                        _ => 0x7C,
                    },
                    _ => match op {
                        BinaryOp::Add => 0x6A,   // i32.add
                        BinaryOp::Sub => 0x6B,   // i32.sub
                        BinaryOp::Mul => 0x6C,   // i32.mul
                        BinaryOp::Div => 0x6D,   // i32.div_s
                        BinaryOp::And => 0x71,   // i32.and
                        BinaryOp::Or => 0x72,    // i32.or
                        BinaryOp::Eq => 0x46,    // i32.eq
                        BinaryOp::NotEq => 0x47, // i32.ne
                        BinaryOp::Lt => 0x48,    // i32.lt_s
                        BinaryOp::Gt => 0x4A,    // i32.gt_s
                        BinaryOp::LtEq => 0x4C,  // i32.le_s
                        BinaryOp::GtEq => 0x4E,  // i32.ge_s
                    },
                };
                body.push(opcode);

                let result_vt = match op {
                    BinaryOp::Eq
                    | BinaryOp::NotEq
                    | BinaryOp::Lt
                    | BinaryOp::Gt
                    | BinaryOp::LtEq
                    | BinaryOp::GtEq
                    | BinaryOp::And
                    | BinaryOp::Or => 0x7F,
                    _ => op_vt,
                };
                Self::emit_wasm_valtype_coercion(result_vt, expected_vt, body);
            }
            Expr::Cast {
                expr: inner,
                target_type,
                ..
            } => {
                let dst_vt = Self::wasm_valtype_byte(target_type);
                let src_vt = Self::infer_wasm_valtype(inner, local_map, fn_index_map)
                    .unwrap_or(dst_vt);
                Self::emit_wasm_expr(inner, src_vt, local_map, fn_index_map, body);
                Self::emit_wasm_valtype_coercion(src_vt, dst_vt, body);
                Self::emit_wasm_valtype_coercion(dst_vt, expected_vt, body);
            }
            Expr::StaticCall { func, args, .. } => {
                for arg in args {
                    let arg_vt =
                        Self::infer_wasm_valtype(arg, local_map, fn_index_map).unwrap_or(0x7F);
                    Self::emit_wasm_expr(arg, arg_vt, local_map, fn_index_map, body);
                }
                if let Some(&(fn_idx, ret_vt)) = fn_index_map.get(func) {
                    body.push(0x10); // call
                    Self::push_u32_leb128(body, fn_idx);
                    Self::emit_wasm_valtype_coercion(ret_vt, expected_vt, body);
                    return;
                }
                body.extend_from_slice(&[0x41, 0x00]);
                Self::emit_wasm_valtype_coercion(0x7F, expected_vt, body);
            }
            _ => {
                body.extend_from_slice(&[0x41, 0x00]);
                Self::emit_wasm_valtype_coercion(0x7F, expected_vt, body);
            }
        }
    }

    fn emit_wasm_valtype_coercion(src_vt: u8, dst_vt: u8, body: &mut Vec<u8>) {
        if src_vt == dst_vt {
            return;
        }
        match (src_vt, dst_vt) {
            (0x7F, 0x7D) => body.push(0xB2), // f32.convert_i32_s
            (0x7D, 0x7F) => body.push(0xA8), // i32.trunc_f32_s
            (0x7F, 0x7C) => body.push(0xB7), // f64.convert_i32_s
            (0x7C, 0x7F) => body.push(0xAA), // i32.trunc_f64_s
            (0x7D, 0x7C) => body.push(0xBB), // f64.promote_f32
            (0x7C, 0x7D) => body.push(0xB6), // f32.demote_f64
            (0x7F, 0x7E) => body.push(0xAC), // i64.extend_i32_s
            (0x7E, 0x7F) => body.push(0xA7), // i32.wrap_i64
            _ => {}
        }
    }

    fn emit_wasm_section(wasm: &mut Vec<u8>, section_id: u8, payload: &[u8]) {
        wasm.push(section_id);
        Self::push_u32_leb128(wasm, payload.len() as u32);
        wasm.extend_from_slice(payload);
    }

    fn push_wasm_export(sec: &mut Vec<u8>, name: &str, kind: u8, index: u32) {
        Self::push_u32_leb128(sec, name.len() as u32);
        sec.extend_from_slice(name.as_bytes());
        sec.push(kind);
        Self::push_u32_leb128(sec, index);
    }

    fn push_u32_leb128(buf: &mut Vec<u8>, mut val: u32) {
        loop {
            let mut byte = (val & 0x7F) as u8;
            val >>= 7;
            if val != 0 {
                byte |= 0x80;
            }
            buf.push(byte);
            if val == 0 {
                break;
            }
        }
    }

    fn push_i64_leb128(buf: &mut Vec<u8>, mut val: i64) {
        loop {
            let byte = (val & 0x7F) as u8;
            val >>= 7;
            let done = (val == 0 && (byte & 0x40) == 0) || (val == -1 && (byte & 0x40) != 0);
            if done {
                buf.push(byte);
                break;
            } else {
                buf.push(byte | 0x80);
            }
        }
    }
}
