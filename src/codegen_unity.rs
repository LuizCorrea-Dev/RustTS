use crate::ast::*;

/// Artefatos gerados pelo backend Unity (`rtsc --target unity` — v1.8.0-rts):
/// 1. Interface nativa `extern "C"` com ponteiros tipados por coluna (`*mut T` / `*const T`) a partir dos parâmetros reais da função.
/// 2. Wrapper C# (`DllImport`) com suporte zero-copy via `NativeArray<T>` e `NativeArrayUnsafeUtility`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UnityPluginOutput {
    pub rust_ffi_code: String,
    pub csharp_wrapper_code: String,
}

pub struct UnityCodegen;

impl UnityCodegen {
    pub fn emit_unity_bindings(module: &Module) -> UnityPluginOutput {
        let mut rust_ffi = String::new();
        let mut csharp = String::new();

        rust_ffi.push_str("// Generated by rtsc 1.8.0-rts --target=unity (Native C-ABI Plugin)\n");
        rust_ffi.push_str("#![allow(clippy::missing_safety_doc, non_snake_case)]\n\n");

        csharp.push_str("// Generated by rtsc 1.8.0-rts --target=unity (Zero-Copy NativeArray C# Bindings)\n");
        csharp.push_str("using System;\nusing System.Runtime.InteropServices;\nusing Unity.Collections;\nusing Unity.Collections.LowLevel.Unsafe;\n\n");
        csharp.push_str("namespace RustTS.Generated\n{\n");

        for item in &module.items {
            if let Item::Struct(s) = item {
                rust_ffi.push_str("#[repr(C, align(16))]\n#[derive(Copy, Clone, Debug)]\n");
                rust_ffi.push_str(&format!("pub struct {} {{\n", s.name));
                for f in &s.fields {
                    rust_ffi.push_str(&format!(
                        "    pub {}: {},\n",
                        f.name,
                        Self::map_rust_ffi_type(&f.ty)
                    ));
                }
                rust_ffi.push_str("}\n\n");

                csharp.push_str("    [StructLayout(LayoutKind.Sequential)]\n");
                csharp.push_str(&format!("    public struct {}\n    {{\n", s.name));
                for f in &s.fields {
                    csharp.push_str(&format!(
                        "        public {} {};\n",
                        Self::map_csharp_type(&f.ty),
                        f.name
                    ));
                }
                csharp.push_str("    }\n\n");
            }
        }

        csharp.push_str("    public static unsafe class RtscNativeBridge\n    {\n");
        csharp.push_str("        private const string DllName = \"rtsc_native_plugin\";\n\n");

        for item in &module.items {
            if let Item::Function(f) = item {
                let mut rust_params = Vec::new();
                let mut pinvoke_params = Vec::new();
                let mut cs_wrapper_params = Vec::new();
                let mut cs_ptr_extractions = Vec::new();
                let mut cs_call_args = Vec::new();
                let mut first_column_name: Option<String> = None;

                for p in &f.params {
                    if let Some(cap) = &p.capability {
                        match (&cap.kind, &cap.generic_arg) {
                            (CapabilityKind::MutColumn, Some(CapGenericArg::TypeName(comp))) => {
                                if first_column_name.is_none() {
                                    first_column_name = Some(p.name.clone());
                                }
                                rust_params.push(format!("{}: *mut {}", p.name, comp));
                                pinvoke_params.push(format!("{}* {}", comp, p.name));
                                cs_wrapper_params.push(format!("NativeArray<{}> {}", comp, p.name));
                                cs_ptr_extractions.push(format!(
                                    "            {}* {}_ptr = ({}*)NativeArrayUnsafeUtility.GetUnsafeBufferPointerWithoutChecks({});",
                                    comp, p.name, comp, p.name
                                ));
                                cs_call_args.push(format!("{}_ptr", p.name));
                            }
                            (CapabilityKind::ReadColumn, Some(CapGenericArg::TypeName(comp))) => {
                                if first_column_name.is_none() {
                                    first_column_name = Some(p.name.clone());
                                }
                                rust_params.push(format!("{}: *const {}", p.name, comp));
                                pinvoke_params.push(format!("{}* {}", comp, p.name));
                                cs_wrapper_params.push(format!(
                                    "NativeArray<{}>.ReadOnly {}",
                                    comp, p.name
                                ));
                                cs_ptr_extractions.push(format!(
                                    "            {}* {}_ptr = ({}*)NativeArrayUnsafeUtility.GetUnsafeReadOnlyPtr({});",
                                    comp, p.name, comp, p.name
                                ));
                                cs_call_args.push(format!("{}_ptr", p.name));
                            }
                            (CapabilityKind::Clock, _) => {
                                rust_params.push("fixed_delta: f32".to_string());
                                pinvoke_params.push("float fixed_delta".to_string());
                                cs_wrapper_params.push("float fixed_delta".to_string());
                                cs_call_args.push("fixed_delta".to_string());
                            }
                            _ => {}
                        }
                    } else {
                        rust_params.push(format!("{}: {}", p.name, Self::map_rust_ffi_type(&p.ty)));
                        pinvoke_params
                            .push(format!("{} {}", Self::map_csharp_type(&p.ty), p.name));
                        cs_wrapper_params
                            .push(format!("{} {}", Self::map_csharp_type(&p.ty), p.name));
                        cs_call_args.push(p.name.clone());
                    }
                }

                rust_params.push("count: usize".to_string());
                pinvoke_params.push("nuint count".to_string());
                if let Some(col) = &first_column_name {
                    cs_call_args.push(format!("(nuint){}.Length", col));
                } else {
                    cs_wrapper_params.push("nuint count".to_string());
                    cs_call_args.push("count".to_string());
                }

                rust_ffi.push_str("#[no_mangle]\n");
                rust_ffi.push_str(&format!(
                    "pub unsafe extern \"C\" fn rts_unity_{}({}) -> u32 {{\n",
                    f.name,
                    rust_params.join(", ")
                ));
                for p in &f.params {
                    if let Some(cap) = &p.capability {
                        if matches!(cap.kind, CapabilityKind::MutColumn | CapabilityKind::ReadColumn)
                        {
                            rust_ffi.push_str(&format!(
                                "    if {}.is_null() {{ return 0; }}\n",
                                p.name
                            ));
                        }
                    }
                }
                let col_names: Vec<String> = f
                    .params
                    .iter()
                    .filter_map(|p| {
                        p.capability.as_ref().and_then(|c| {
                            if matches!(c.kind, CapabilityKind::MutColumn | CapabilityKind::ReadColumn)
                            {
                                Some(p.name.clone())
                            } else {
                                None
                            }
                        })
                    })
                    .collect();

                rust_ffi.push_str("    let mut processed: u32 = 0;\n");
                for stmt in &f.body {
                    Self::lower_unity_rust_stmt(&mut rust_ffi, stmt, 1, &col_names);
                }
                rust_ffi.push_str("    processed\n}\n\n");

                csharp.push_str("        [DllImport(DllName, CallingConvention = CallingConvention.Cdecl)]\n");
                csharp.push_str(&format!(
                    "        private static extern uint rts_unity_{}({});\n\n",
                    f.name,
                    pinvoke_params.join(", ")
                ));

                csharp.push_str(&format!(
                    "        public static uint Invoke_{}({})\n        {{\n",
                    f.name,
                    cs_wrapper_params.join(", ")
                ));
                for line in &cs_ptr_extractions {
                    csharp.push_str(line);
                    csharp.push('\n');
                }
                csharp.push_str(&format!(
                    "            return rts_unity_{}({});\n        }}\n\n",
                    f.name,
                    cs_call_args.join(", ")
                ));
            }
        }

        csharp.push_str("    }\n}\n");

        UnityPluginOutput {
            rust_ffi_code: rust_ffi,
            csharp_wrapper_code: csharp,
        }
    }

    fn lower_unity_rust_stmt(
        out: &mut String,
        stmt: &Stmt,
        indent: usize,
        col_names: &[String],
    ) {
        let pad = "    ".repeat(indent);
        match stmt {
            Stmt::Let {
                name,
                is_mut,
                value,
                ..
            } => {
                let mut_kw = if *is_mut { "mut " } else { "" };
                out.push_str(&format!(
                    "{}let {}{} = {};\n",
                    pad,
                    mut_kw,
                    name,
                    Self::lower_unity_rust_expr(value, col_names)
                ));
            }
            Stmt::Assign { target, value, .. } => {
                out.push_str(&format!(
                    "{}{} = {};\n",
                    pad,
                    Self::lower_unity_rust_expr(target, col_names),
                    Self::lower_unity_rust_expr(value, col_names)
                ));
            }
            Stmt::If {
                condition,
                then_branch,
                else_branch,
                ..
            } => {
                out.push_str(&format!(
                    "{}if {} {{\n",
                    pad,
                    Self::lower_unity_rust_expr(condition, col_names)
                ));
                for s in then_branch {
                    Self::lower_unity_rust_stmt(out, s, indent + 1, col_names);
                }
                if let Some(eb) = else_branch {
                    out.push_str(&format!("{}}} else {{\n", pad));
                    for s in eb {
                        Self::lower_unity_rust_stmt(out, s, indent + 1, col_names);
                    }
                }
                out.push_str(&format!("{}}}\n", pad));
            }
            Stmt::While {
                condition, body, ..
            } => {
                out.push_str(&format!(
                    "{}while {} {{\n",
                    pad,
                    Self::lower_unity_rust_expr(condition, col_names)
                ));
                for s in body {
                    Self::lower_unity_rust_stmt(out, s, indent + 1, col_names);
                }
                out.push_str(&format!("{}}}\n", pad));
            }
            Stmt::Break { .. } => out.push_str(&format!("{}break;\n", pad)),
            Stmt::Continue { .. } => out.push_str(&format!("{}continue;\n", pad)),
            Stmt::ForRange { iterator, body, .. } => {
                out.push_str(&format!("{}for {} in 0..count {{\n", pad, iterator));
                for s in body {
                    Self::lower_unity_rust_stmt(out, s, indent + 1, col_names);
                }
                out.push_str(&format!(
                    "{}    processed = processed.wrapping_add(1);\n",
                    pad
                ));
                out.push_str(&format!("{}}}\n", pad));
            }
            Stmt::Match { arms, .. } => {
                for arm in arms {
                    for s in &arm.body {
                        Self::lower_unity_rust_stmt(out, s, indent, col_names);
                    }
                }
            }
            Stmt::Return { .. } | Stmt::ExprStmt { .. } => {}
        }
    }

    fn lower_unity_rust_expr(expr: &Expr, col_names: &[String]) -> String {
        match expr {
            Expr::IntLit(v, _) => format!("{}", v),
            Expr::FloatLit(v, _) => {
                let s = format!("{}", v);
                if s.contains('.') {
                    format!("{}_f32", s)
                } else {
                    format!("{}.0_f32", s)
                }
            }
            Expr::BoolLit(b, _) => b.to_string(),
            Expr::Ident(name, _) => name.clone(),
            Expr::FieldAccess {
                receiver, field, ..
            } => {
                if field == "fixed_delta" {
                    return "fixed_delta".to_string();
                }
                if let Expr::Index {
                    receiver: col_rec,
                    index,
                    ..
                } = receiver.as_ref()
                {
                    if let Expr::Ident(col_name, _) = col_rec.as_ref() {
                        if col_names.contains(col_name) {
                            return format!(
                                "(*{}.add({})).{}",
                                col_name,
                                Self::lower_unity_rust_expr(index, col_names),
                                field
                            );
                        }
                    }
                }
                format!(
                    "{}.{}",
                    Self::lower_unity_rust_expr(receiver, col_names),
                    field
                )
            }
            Expr::Index {
                receiver, index, ..
            } => {
                let rec = Self::lower_unity_rust_expr(receiver, col_names);
                let idx = Self::lower_unity_rust_expr(index, col_names);
                if col_names.iter().any(|c| c == &rec) {
                    format!("(*{}.add({}))", rec, idx)
                } else {
                    format!("{}[{}]", rec, idx)
                }
            }
            Expr::MethodCall { method, .. } if method == "len" => "count".to_string(),
            Expr::Binary {
                left, op, right, ..
            } => {
                let l = Self::lower_unity_rust_expr(left, col_names);
                let r = Self::lower_unity_rust_expr(right, col_names);
                let op_str = match op {
                    BinaryOp::Add => "+",
                    BinaryOp::Sub => "-",
                    BinaryOp::Mul => "*",
                    BinaryOp::Div => "/",
                    BinaryOp::Eq => "==",
                    BinaryOp::NotEq => "!=",
                    BinaryOp::Lt => "<",
                    BinaryOp::LtEq => "<=",
                    BinaryOp::Gt => ">",
                    BinaryOp::GtEq => ">=",
                    BinaryOp::And => "&&",
                    BinaryOp::Or => "||",
                };
                format!("({} {} {})", l, op_str, r)
            }
            Expr::Unary { op, expr: inner, .. } => {
                let op_str = match op {
                    UnaryOp::Neg => "-",
                    UnaryOp::Not => "!",
                };
                format!(
                    "({}{})",
                    op_str,
                    Self::lower_unity_rust_expr(inner, col_names)
                )
            }
            _ => "0".to_string(),
        }
    }

    fn map_rust_ffi_type(ty: &TypeExpr) -> String {
        match ty {
            TypeExpr::Primitive(PrimitiveType::F32) => "f32".to_string(),
            TypeExpr::Primitive(PrimitiveType::F64) => "f64".to_string(),
            TypeExpr::Primitive(PrimitiveType::I32) => "i32".to_string(),
            TypeExpr::Primitive(PrimitiveType::U32) => "u32".to_string(),
            TypeExpr::Primitive(PrimitiveType::U64) => "u64".to_string(),
            TypeExpr::Primitive(PrimitiveType::U8) => "u8".to_string(),
            TypeExpr::Primitive(PrimitiveType::Bool) => "bool".to_string(),
            TypeExpr::Math(MathType::Vec2) => "[f32; 2]".to_string(),
            TypeExpr::Math(MathType::Vec3) => "[f32; 3]".to_string(),
            TypeExpr::Math(MathType::Vec4) | TypeExpr::Math(MathType::Quat) => "[f32; 4]".to_string(),
            TypeExpr::Handle(_) => "u64".to_string(),
            TypeExpr::Named { name, .. } => name.clone(),
            _ => "*mut core::ffi::c_void".to_string(),
        }
    }

    fn map_csharp_type(ty: &TypeExpr) -> &'static str {
        match ty {
            TypeExpr::Primitive(PrimitiveType::F32) => "float",
            TypeExpr::Primitive(PrimitiveType::F64) => "double",
            TypeExpr::Primitive(PrimitiveType::I32) => "int",
            TypeExpr::Primitive(PrimitiveType::U32) => "uint",
            TypeExpr::Primitive(PrimitiveType::U64) => "ulong",
            TypeExpr::Primitive(PrimitiveType::U8) => "byte",
            TypeExpr::Primitive(PrimitiveType::Bool) => "bool",
            TypeExpr::Math(MathType::Vec2) => "UnityEngine.Vector2",
            TypeExpr::Math(MathType::Vec3) => "UnityEngine.Vector3",
            TypeExpr::Math(MathType::Vec4) => "UnityEngine.Vector4",
            TypeExpr::Math(MathType::Quat) => "UnityEngine.Quaternion",
            TypeExpr::Handle(_) => "ulong",
            _ => "IntPtr",
        }
    }
}
