    fn lower_lvalue_ptr(
        out: &mut String,
        expr: &Expr,
        ctx: &mut LlvmLoweringCtx,
    ) -> Option<(String, String)> {
        match expr {
            Expr::Ident(name, _) => ctx.var_ptrs.get(name).cloned(),
            Expr::FieldAccess {
                receiver, field, ..
            } => {
                let (rec_ptr, rec_ty) = Self::lower_lvalue_ptr(out, receiver, ctx)?;
                if rec_ty.starts_with('%') && rec_ty.ends_with("_t") {
                    let s_name = &rec_ty[1..rec_ty.len() - 2];
                    if let Some((f_idx, f_ty)) = ctx
                        .struct_field_indices
                        .get(&(s_name.to_string(), field.clone()))
                        .cloned()
                    {
                        let gep = ctx.next_reg();
                        out.push_str(&format!(
                            "  {} = getelementptr inbounds {}, ptr {}, i32 0, i32 {}\n",
                            gep, rec_ty, rec_ptr, f_idx
                        ));
                        return Some((gep, f_ty));
                    }
                }
                None
            }
            Expr::Index {
                receiver, index, ..
            } => {
                let (arr_ptr, arr_ty) = Self::lower_lvalue_ptr(out, receiver, ctx)?;
                if arr_ty.starts_with('[') && arr_ty.ends_with(']') {
                    let inner = &arr_ty[1..arr_ty.len() - 1];
                    if let Some((_, elem_ty)) = inner.split_once(" x ") {
                        let (idx_v, idx_t) = Self::lower_expr(out, index, ctx, Some("i64"));
                        let idx64 = Self::coerce_scalar(out, ctx, &idx_v, &idx_t, "i64");
                        let gep = ctx.next_reg();
                        out.push_str(&format!(
                            "  {} = getelementptr inbounds {}, ptr {}, i64 0, i64 {}\n",
                            gep, arr_ty, arr_ptr, idx64
                        ));
                        return Some((gep, elem_ty.to_string()));
                    }
                }
                None
            }
            _ => None,
        }
    }

