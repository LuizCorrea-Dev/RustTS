use crate::ast::*;
use std::collections::{HashMap, HashSet};

/// Gerador Direto de LLVM IR SSA (`rtsc --target=llvm-ir` — v1.9.0-rts Cycle 2 Phase 7).
/// Compila a AST tipada da RustTS diretamente para LLVM IR moderno (opaque pointers `ptr`,
/// LLVM 15–22+), emitindo:
/// 1. Ponteiros `ptr noalias nocapture noundef align 64` para colunas SoA de 64 bytes.
/// 2. Instruções `fadd fast`, `fmul fast`, intrínsecos `@llvm.sqrt.f32`, `@llvm.sin.f32`,
///    `@llvm.cos.f32`, `@llvm.fabs.f32` e metadados de vetorização `!llvm.loop.vectorize.width = 8`.
/// 3. Código `.ll` 100% compatível com compilação direta via `clang -x ir -O3 -mavx2 -mfma` sem C99.
pub struct LlvmIrCodegen;

#[derive(Clone, Default)]
struct LlvmLoweringCtx {
    reg_counter: usize,
    label_counter: usize,
    mod_prefix: String,
    module_fn_names: HashSet<String>,
    extern_fns: HashMap<String, (Vec<bool>, Vec<String>, Option<String>)>,
    fn_return_types: HashMap<String, Option<String>>,
    fn_param_types: HashMap<String, Vec<String>>,
    struct_field_indices: HashMap<(String, String), (usize, String)>,
    component_soa_fields: HashMap<(String, String), usize>,
    var_ptrs: HashMap<String, (String, String)>,
    param_vals: HashMap<String, (String, String)>,
    local_struct_names: HashMap<String, String>,
    soa_columns: HashMap<String, String>,
    string_pool: Vec<(String, String, usize)>,
    loop_exit_stack: Vec<(String, String)>,
    block_terminated: bool,
}

impl LlvmLoweringCtx {
    fn next_reg(&mut self) -> String {
        let id = self.reg_counter;
        self.reg_counter += 1;
        format!("%r{}", id)
    }

    fn next_label_id(&mut self) -> usize {
        let id = self.label_counter;
        self.label_counter += 1;
        id
    }

    fn intern_string(&mut self, s: &str) -> (String, usize) {
        for (glob, content, byte_len) in &self.string_pool {
            if content == s {
                return (glob.clone(), *byte_len);
            }
        }
        let id = self.string_pool.len();
        let glob = format!("@.str.{}", id);
        let byte_len = s.len() + 1;
        self.string_pool.push((glob.clone(), s.to_string(), byte_len));
        (glob, byte_len)
    }
}

impl LlvmIrCodegen {
    pub fn emit_llvm_ir(module: &Module) -> String {
        let mut out = String::new();
        let mod_name = if module.path.is_empty() {
            "root".to_string()
        } else {
            module.path.join("_")
        };

        let (datalayout, triple) = if cfg!(all(target_os = "windows", target_arch = "x86_64")) {
            (
                "e-m:w-p270:32:32-p271:32:32-p272:64:64-i64:64-i128:128-f80:128-n8:16:32:64-S128",
                "x86_64-pc-windows-msvc",
            )
        } else if cfg!(all(target_os = "macos", target_arch = "aarch64")) {
            (
                "e-m:o-i64:64-i128:128-n32:64-S128",
                "aarch64-apple-darwin",
            )
        } else {
            (
                "e-m:e-p270:32:32-p271:32:32-p272:64:64-i64:64-i128:128-f80:128-n8:16:32:64-S128",
                "x86_64-unknown-linux-gnu",
            )
        };

        out.push_str(&format!(
            "; ==========================================================================\n\
             ; Generated by rtsc 1.9.0-rts --target=llvm-ir (Direct SSA & SIMD LLVM IR)\n\
             ; Source Module: {}\n\
             ; Guarantees:\n\
             ;   1. Opaque Pointers (`ptr noalias align 64`) for 64B SoA Descriptors\n\
             ;   2. Fast-Math Vectorizable SSA Loops (`!llvm.loop.vectorize.width = 8`)\n\
             ;   3. Zero-Overhead Capability Stripping on Native C-ABI & Intrinsics\n\
             ; ==========================================================================\n\n\
             source_filename = \"{}.rts\"\n\
             target datalayout = \"{}\"\n\
             target triple = \"{}\"\n\n",
            module.path.join("."),
            mod_name,
            datalayout,
            triple
        ));

        out.push_str("%rts_vec2_t = type { float, float }\n");
        out.push_str("%rts_vec3_t = type { float, float, float }\n");
        out.push_str("%rts_vec4_t = type { float, float, float, float }\n");
        out.push_str("%rts_quat_t = type { float, float, float, float }\n");
        out.push_str("%TimeStep_t = type { float }\n\n");

        let mut struct_field_indices: HashMap<(String, String), (usize, String)> = HashMap::new();
        let mut component_soa_fields: HashMap<(String, String), usize> = HashMap::new();

        // 1. Emissão de Tipos de Structs e Descritores SoA de 64 Bytes
        for item in &module.items {
            if let Item::Struct(s) = item {
                let mut field_tys = Vec::new();
                for (idx, f) in s.fields.iter().enumerate() {
                    let ll_ty = Self::map_llvm_type(&f.ty);
                    struct_field_indices
                        .insert((s.name.clone(), f.name.clone()), (idx, ll_ty.clone()));
                    field_tys.push(ll_ty);
                }
                out.push_str(&format!(
                    "%{}_t = type {{ {} }}\n",
                    s.name,
                    field_tys.join(", ")
                ));

                let is_comp = s
                    .attributes
                    .iter()
                    .any(|a| matches!(a, Attribute::Component));
                if is_comp {
                    let mut soa_ptrs = Vec::new();
                    let mut ptr_idx = 0usize;
                    for f in &s.fields {
                        match &f.ty {
                            TypeExpr::Math(m @ (MathType::Vec2 | MathType::Vec3 | MathType::Vec4 | MathType::Quat)) => {
                                let lanes = match m {
                                    MathType::Vec2 => &["x", "y"][..],
                                    MathType::Vec3 => &["x", "y", "z"][..],
                                    _ => &["x", "y", "z", "w"][..],
                                };
                                for lane in lanes {
                                    component_soa_fields.insert(
                                        (s.name.clone(), format!("{}.{}", f.name, lane)),
                                        ptr_idx,
                                    );
                                    if *lane == "x" {
                                        component_soa_fields
                                            .insert((s.name.clone(), f.name.clone()), ptr_idx);
                                    }
                                    soa_ptrs.push("ptr".to_string());
                                    ptr_idx += 1;
                                }
                            }
                            _ => {
                                component_soa_fields
                                    .insert((s.name.clone(), f.name.clone()), ptr_idx);
                                soa_ptrs.push("ptr".to_string());
                                ptr_idx += 1;
                            }
                        }
                    }
                    // Ponteiro de handles + count (i64) + capacity (i64)
                    soa_ptrs.push("ptr".to_string());
                    soa_ptrs.push("i64".to_string());
                    soa_ptrs.push("i64".to_string());
                    out.push_str(&format!(
                        "%{}_soa_column_t = type {{ {} }}\n",
                        s.name,
                        soa_ptrs.join(", ")
                    ));
                }
            }
        }
        out.push('\n');

        // 2. Declarações Intrínsecas LLVM e C Runtime
        out.push_str("; --- LLVM Hardware & Math Intrinsics ---\n");
        out.push_str("declare i32 @printf(ptr nocapture noundef readonly, ...)\n");
        out.push_str("declare float @llvm.sqrt.f32(float)\n");
        out.push_str("declare float @llvm.sin.f32(float)\n");
        out.push_str("declare float @llvm.cos.f32(float)\n");
        out.push_str("declare float @llvm.fabs.f32(float)\n");
        out.push_str("declare float @llvm.floor.f32(float)\n");
        out.push_str("declare float @llvm.ceil.f32(float)\n");
        out.push_str("declare float @llvm.round.f32(float)\n");
        out.push_str("declare float @llvm.fmuladd.f32(float, float, float)\n");
        out.push_str("declare <8 x float> @llvm.fmuladd.v8f32(<8 x float>, <8 x float>, <8 x float>)\n");

        let mut module_fn_names: HashSet<String> = HashSet::new();
        let mut fn_return_types: HashMap<String, Option<String>> = HashMap::new();
        let mut fn_param_types: HashMap<String, Vec<String>> = HashMap::new();
        let mut extern_fns: HashMap<String, (Vec<bool>, Vec<String>, Option<String>)> =
            HashMap::new();

        for item in &module.items {
            match item {
                Item::Function(f) => {
                    module_fn_names.insert(f.name.clone());
                    let ret_ll = f.return_type.as_ref().map(Self::map_llvm_type);
                    fn_return_types.insert(f.name.clone(), ret_ll);
                    let p_tys: Vec<String> = f
                        .params
                        .iter()
                        .map(Self::map_param_llvm_type)
                        .collect();
                    fn_param_types.insert(f.name.clone(), p_tys);
                }
                Item::ExternFn(ext) => {
                    let mut cap_mask = Vec::new();
                    let mut runtime_tys = Vec::new();
                    for p in &ext.params {
                        if p.is_cap {
                            cap_mask.push(true);
                        } else {
                            cap_mask.push(false);
                            runtime_tys.push(Self::map_llvm_type(&p.ty));
                        }
                    }
                    let ret_ll = ext.return_type.as_ref().map(Self::map_llvm_type);
                    let ret_str = ret_ll.clone().unwrap_or_else(|| "void".to_string());
                    out.push_str(&format!(
                        "declare {} @{}({})\n",
                        ret_str,
                        ext.name,
                        runtime_tys.join(", ")
                    ));
                    extern_fns.insert(ext.name.clone(), (cap_mask, runtime_tys, ret_ll.clone()));
                    fn_return_types.insert(ext.name.clone(), ret_ll);
                }
                _ => {}
            }
        }
        out.push('\n');

        let mut global_string_pool: Vec<(String, String, usize)> = Vec::new();
        // Format strings padrão para `io::println`, `io::print_f32`, `io::print_i32`, `io::print_u32`
        global_string_pool.push(("@.str.fmt_ln".to_string(), "%s\n".to_string(), 4));
        global_string_pool.push(("@.str.fmt_f32".to_string(), "%s%.2f\n".to_string(), 8));
        global_string_pool.push(("@.str.fmt_i32".to_string(), "%s%d\n".to_string(), 6));
        global_string_pool.push(("@.str.fmt_u32".to_string(), "%s%u\n".to_string(), 6));

        let mut functions_ir = String::new();

        // 3. Emissão de Funções (`define dso_local ...`)
        for item in &module.items {
            if let Item::Function(f) = item {
                let mut ctx = LlvmLoweringCtx {
                    reg_counter: 0,
                    label_counter: 0,
                    mod_prefix: mod_name.clone(),
                    module_fn_names: module_fn_names.clone(),
                    extern_fns: extern_fns.clone(),
                    fn_return_types: fn_return_types.clone(),
                    fn_param_types: fn_param_types.clone(),
                    struct_field_indices: struct_field_indices.clone(),
                    component_soa_fields: component_soa_fields.clone(),
                    string_pool: global_string_pool.clone(),
                    ..Default::default()
                };

                let is_main = f.name == "main";
                let fn_sym = if is_main {
                    "main".to_string()
                } else {
                    format!("{}_{}", mod_name, f.name)
                };

                let ret_ll = if is_main && f.return_type.is_none() {
                    Some("i32".to_string())
                } else {
                    f.return_type.as_ref().map(Self::map_llvm_type)
                };
                let ret_sig = ret_ll.clone().unwrap_or_else(|| "void".to_string());

                let mut param_sigs = Vec::new();
                if !is_main {
                    for p in &f.params {
                        let p_ty = Self::map_param_llvm_type(p);
                        let p_reg = format!("%arg_{}", p.name);
                        if let Some(cap) = &p.capability {
                            match (&cap.kind, &cap.generic_arg) {
                                (CapabilityKind::MutColumn, Some(CapGenericArg::TypeName(t)))
                                | (CapabilityKind::ReadColumn, Some(CapGenericArg::TypeName(t))) => {
                                    ctx.soa_columns.insert(p.name.clone(), t.clone());
                                    param_sigs.push(format!(
                                        "ptr noalias nocapture noundef align 64 {}",
                                        p_reg
                                    ));
                                }
                                _ => {
                                    param_sigs.push(format!("ptr noalias noundef {}", p_reg));
                                }
                            }
                        } else {
                            param_sigs.push(format!("{} {}", p_ty, p_reg));
                        }
                        ctx.param_vals
                            .insert(p.name.clone(), (p_reg, p_ty));
                        if let TypeExpr::Named { name, .. } = &p.ty {
                            ctx.local_struct_names.insert(p.name.clone(), name.clone());
                        }
                    }
                }

                functions_ir.push_str(&format!(
                    "define dso_local {} @{}({}) #0 {{\nentry:\n",
                    ret_sig,
                    fn_sym,
                    param_sigs.join(", ")
                ));

                // Promove parâmetros escalares/structs para stack slots (`alloca`) para permitir mutação/acesso uniforme
                if !is_main {
                    for p in &f.params {
                        if !p.is_cap {
                            let p_ty = Self::map_param_llvm_type(p);
                            let slot = format!("%slot_{}", p.name);
                            functions_ir.push_str(&format!("  {} = alloca {}, align 4\n", slot, p_ty));
                            functions_ir.push_str(&format!(
                                "  store {} %arg_{}, ptr {}, align 4\n",
                                p_ty, p.name, slot
                            ));
                            ctx.var_ptrs.insert(p.name.clone(), (slot, p_ty));
                        }
                    }
                }

                for stmt in &f.body {
                    if ctx.block_terminated {
                        break;
                    }
                    Self::lower_stmt(&mut functions_ir, stmt, &mut ctx, &ret_ll);
                }

                if !ctx.block_terminated {
                    match &ret_ll {
                        Some(r) if r == "float" || r == "double" => {
                            functions_ir.push_str(&format!("  ret {} 0.0\n", r));
                        }
                        Some(r) if r.starts_with('%') || r.starts_with('{') => {
                            functions_ir.push_str(&format!("  ret {} zeroinitializer\n", r));
                        }
                        Some(r) => {
                            functions_ir.push_str(&format!("  ret {} 0\n", r));
                        }
                        None => {
                            functions_ir.push_str("  ret void\n");
                        }
                    }
                }

                functions_ir.push_str("}\n\n");
                global_string_pool = ctx.string_pool;
            }
        }

        // 4. Emissão da Tabela de Strings Constantes (`@.str.*`)
        out.push_str("; --- Constant UTF-8 String Pool ---\n");
        for (glob, content, byte_len) in &global_string_pool {
            let escaped = Self::escape_llvm_string(content);
            out.push_str(&format!(
                "{} = private unnamed_addr constant [{} x i8] c\"{}\\00\", align 1\n",
                glob, byte_len, escaped
            ));
        }
        out.push('\n');

        out.push_str(&functions_ir);

        out.push_str("attributes #0 = { nounwind uwtable \"frame-pointer\"=\"none\" \"target-cpu\"=\"x86-64-v3\" }\n\n");
        out.push_str("!0 = distinct !{!0, !1, !2}\n");
        out.push_str("!1 = !{!\"llvm.loop.vectorize.enable\", i1 true}\n");
        out.push_str("!2 = !{!\"llvm.loop.vectorize.width\", i32 8}\n");

        out
    }

    fn lower_stmt(
        out: &mut String,
        stmt: &Stmt,
        ctx: &mut LlvmLoweringCtx,
        fn_ret: &Option<String>,
    ) {
        match stmt {
            Stmt::Let {
                name, ty, value, ..
            } => {
                if let Some(TypeExpr::Capability(_)) = ty {
                    let slot = format!("%cap_{}", name);
                    out.push_str(&format!("  {} = alloca i64, align 8\n", slot));
                    out.push_str(&format!("  store i64 0, ptr {}, align 8\n", slot));
                    ctx.param_vals
                        .insert(name.clone(), (slot, "ptr".to_string()));
                    return;
                }

                if let Some(TypeExpr::Named { name: s_name, .. }) = ty {
                    ctx.local_struct_names.insert(name.clone(), s_name.clone());
                } else if let Expr::StructInit { struct_name, .. } = value {
                    ctx.local_struct_names
                        .insert(name.clone(), struct_name.clone());
                }

                // Array literal `let pesos = [1.0, 2.0, 3.0, 4.0];`
                if let Expr::ArrayLit { elements, .. } = value {
                    let elem_ty = match ty {
                        Some(TypeExpr::Array(inner, _)) => Self::map_llvm_type(inner),
                        _ => "float".to_string(),
                    };
                    let arr_ty = format!("[{} x {}]", elements.len(), elem_ty);
                    let slot = ctx.next_reg();
                    out.push_str(&format!("  {} = alloca {}, align 16\n", slot, arr_ty));
                    for (idx, el) in elements.iter().enumerate() {
                        let (el_v, _) = Self::lower_expr(out, el, ctx, Some(&elem_ty));
                        let gep = ctx.next_reg();
                        out.push_str(&format!(
                            "  {} = getelementptr inbounds {}, ptr {}, i64 0, i64 {}\n",
                            gep, arr_ty, slot, idx
                        ));
                        out.push_str(&format!(
                            "  store {} {}, ptr {}, align 4\n",
                            elem_ty, el_v, gep
                        ));
                    }
                    ctx.var_ptrs.insert(name.clone(), (slot, arr_ty));
                    return;
                }

                let explicit_ty = ty.as_ref().map(Self::map_llvm_type);
                let (val_reg, val_ty) =
                    Self::lower_expr(out, value, ctx, explicit_ty.as_deref());
                let final_ty = explicit_ty.unwrap_or_else(|| val_ty.clone());
                let coerced_reg = Self::coerce_scalar(out, ctx, &val_reg, &val_ty, &final_ty);

                let slot = ctx.next_reg();
                out.push_str(&format!("  {} = alloca {}, align 8\n", slot, final_ty));
                out.push_str(&format!(
                    "  store {} {}, ptr {}, align 4\n",
                    final_ty, coerced_reg, slot
                ));
                ctx.var_ptrs.insert(name.clone(), (slot, final_ty));
            }

            Stmt::Assign { target, value, .. } => {
                // Caso 1: Escrita em coluna SoA `pos[i].py = ny;`
                if let Expr::FieldAccess {
                    receiver, field, ..
                } = target
                {
                    if let Expr::Index {
                        receiver: col_expr,
                        index,
                        ..
                    } = receiver.as_ref()
                    {
                        if let Expr::Ident(col_name, _) = col_expr.as_ref() {
                            if let Some(comp_name) = ctx.soa_columns.get(col_name).cloned() {
                                let field_idx = ctx
                                    .component_soa_fields
                                    .get(&(comp_name.clone(), field.clone()))
                                    .copied()
                                    .unwrap_or(0);
                                let col_reg = ctx
                                    .param_vals
                                    .get(col_name)
                                    .map(|(r, _)| r.clone())
                                    .unwrap_or_else(|| format!("%arg_{}", col_name));
                                let (idx_v, idx_t) =
                                    Self::lower_expr(out, index, ctx, Some("i64"));
                                let idx_64 = Self::ensure_i64(out, ctx, &idx_v, &idx_t);
                                let (val_v, _) = Self::lower_expr(out, value, ctx, Some("float"));

                                let field_ptr_gep = ctx.next_reg();
                                out.push_str(&format!(
                                    "  {} = getelementptr inbounds %{}_soa_column_t, ptr {}, i32 0, i32 {}\n",
                                    field_ptr_gep, comp_name, col_reg, field_idx
                                ));
                                let base_ptr = ctx.next_reg();
                                out.push_str(&format!(
                                    "  {} = load ptr, ptr {}, align 8\n",
                                    base_ptr, field_ptr_gep
                                ));
                                let elem_gep = ctx.next_reg();
                                out.push_str(&format!(
                                    "  {} = getelementptr inbounds float, ptr {}, i64 {}\n",
                                    elem_gep, base_ptr, idx_64
                                ));
                                out.push_str(&format!(
                                    "  store float {}, ptr {}, align 4\n",
                                    val_v, elem_gep
                                ));
                                return;
                            }
                        }
                    }
                }

                // Caso 2: Variável local mutável
                if let Expr::Ident(var_name, _) = target {
                    if let Some((slot, var_ty)) = ctx.var_ptrs.get(var_name).cloned() {
                        let (val_v, _) = Self::lower_expr(out, value, ctx, Some(&var_ty));
                        out.push_str(&format!(
                            "  store {} {}, ptr {}, align 4\n",
                            var_ty, val_v, slot
                        ));
                    }
                }
            }

            Stmt::If {
                condition,
                then_branch,
                else_branch,
                ..
            } => {
                let (cond_v, cond_t) = Self::lower_expr(out, condition, ctx, Some("i1"));
                let cond_i1 = Self::ensure_i1(out, ctx, &cond_v, &cond_t);
                let id = ctx.next_label_id();
                let then_lbl = format!("if.then.{}", id);
                let else_lbl = format!("if.else.{}", id);
                let end_lbl = format!("if.end.{}", id);

                if else_branch.is_some() {
                    out.push_str(&format!(
                        "  br i1 {}, label %{}, label %{}\n",
                        cond_i1, then_lbl, else_lbl
                    ));
                } else {
                    out.push_str(&format!(
                        "  br i1 {}, label %{}, label %{}\n",
                        cond_i1, then_lbl, end_lbl
                    ));
                }

                out.push_str(&format!("{}:\n", then_lbl));
                ctx.block_terminated = false;
                for s in then_branch {
                    if ctx.block_terminated {
                        break;
                    }
                    Self::lower_stmt(out, s, ctx, fn_ret);
                }
                let then_terminated = ctx.block_terminated;
                if !then_terminated {
                    out.push_str(&format!("  br label %{}\n", end_lbl));
                }

                if let Some(eb) = else_branch {
                    out.push_str(&format!("{}:\n", else_lbl));
                    ctx.block_terminated = false;
                    for s in eb {
                        if ctx.block_terminated {
                            break;
                        }
                        Self::lower_stmt(out, s, ctx, fn_ret);
                    }
                    let else_terminated = ctx.block_terminated;
                    if !else_terminated {
                        out.push_str(&format!("  br label %{}\n", end_lbl));
                    }
                }

                out.push_str(&format!("{}:\n", end_lbl));
                ctx.block_terminated = false;
            }

            Stmt::While {
                condition, body, ..
            } => {
                let id = ctx.next_label_id();
                let cond_lbl = format!("while.cond.{}", id);
                let body_lbl = format!("while.body.{}", id);
                let end_lbl = format!("while.end.{}", id);

                out.push_str(&format!("  br label %{}\n", cond_lbl));
                out.push_str(&format!("{}:\n", cond_lbl));
                ctx.block_terminated = false;
                let (cond_v, cond_t) = Self::lower_expr(out, condition, ctx, Some("i1"));
                let cond_i1 = Self::ensure_i1(out, ctx, &cond_v, &cond_t);
                out.push_str(&format!(
                    "  br i1 {}, label %{}, label %{}\n",
                    cond_i1, body_lbl, end_lbl
                ));

                out.push_str(&format!("{}:\n", body_lbl));
                ctx.block_terminated = false;
                ctx.loop_exit_stack
                    .push((cond_lbl.clone(), end_lbl.clone()));
                for s in body {
                    if ctx.block_terminated {
                        break;
                    }
                    Self::lower_stmt(out, s, ctx, fn_ret);
                }
                ctx.loop_exit_stack.pop();
                if !ctx.block_terminated {
                    out.push_str(&format!("  br label %{}\n", cond_lbl));
                }

                out.push_str(&format!("{}:\n", end_lbl));
                ctx.block_terminated = false;
            }

            Stmt::ForRange {
                iterator,
                start,
                end,
                body,
                ..
            } => {
                let (s_v, s_t) = Self::lower_expr(out, start, ctx, Some("i64"));
                let s_64 = Self::ensure_i64(out, ctx, &s_v, &s_t);
                let (e_v, e_t) = Self::lower_expr(out, end, ctx, Some("i64"));
                let e_64 = Self::ensure_i64(out, ctx, &e_v, &e_t);

                let iter_slot = ctx.next_reg();
                out.push_str(&format!("  {} = alloca i64, align 8\n", iter_slot));
                out.push_str(&format!("  store i64 {}, ptr {}, align 8\n", s_64, iter_slot));
                ctx.var_ptrs
                    .insert(iterator.clone(), (iter_slot.clone(), "i64".to_string()));

                let id = ctx.next_label_id();
                let cond_lbl = format!("for.cond.{}", id);
                let body_lbl = format!("for.body.{}", id);
                let inc_lbl = format!("for.inc.{}", id);
                let end_lbl = format!("for.end.{}", id);

                out.push_str(&format!("  br label %{}\n", cond_lbl));
                out.push_str(&format!("{}:\n", cond_lbl));
                let cur_i = ctx.next_reg();
                out.push_str(&format!("  {} = load i64, ptr {}, align 8\n", cur_i, iter_slot));
                let cmp_r = ctx.next_reg();
                out.push_str(&format!(
                    "  {} = icmp ult i64 {}, {}\n",
                    cmp_r, cur_i, e_64
                ));
                out.push_str(&format!(
                    "  br i1 {}, label %{}, label %{}\n",
                    cmp_r, body_lbl, end_lbl
                ));

                out.push_str(&format!("{}:\n", body_lbl));
                ctx.block_terminated = false;
                ctx.loop_exit_stack.push((inc_lbl.clone(), end_lbl.clone()));
                for s in body {
                    if ctx.block_terminated {
                        break;
                    }
                    Self::lower_stmt(out, s, ctx, fn_ret);
                }
                ctx.loop_exit_stack.pop();
                if !ctx.block_terminated {
                    out.push_str(&format!("  br label %{}\n", inc_lbl));
                }

                out.push_str(&format!("{}:\n", inc_lbl));
                let prev_i = ctx.next_reg();
                out.push_str(&format!("  {} = load i64, ptr {}, align 8\n", prev_i, iter_slot));
                let next_i = ctx.next_reg();
                out.push_str(&format!("  {} = add i64 {}, 1\n", next_i, prev_i));
                out.push_str(&format!(
                    "  store i64 {}, ptr {}, align 8\n",
                    next_i, iter_slot
                ));
                out.push_str(&format!("  br label %{}, !llvm.loop !0\n", cond_lbl));

                out.push_str(&format!("{}:\n", end_lbl));
                ctx.block_terminated = false;
            }

            Stmt::Break { .. } => {
                if let Some((_, end_lbl)) = ctx.loop_exit_stack.last() {
                    out.push_str(&format!("  br label %{}\n", end_lbl));
                    ctx.block_terminated = true;
                }
            }

            Stmt::Continue { .. } => {
                if let Some((step_lbl, _)) = ctx.loop_exit_stack.last() {
                    out.push_str(&format!("  br label %{}\n", step_lbl));
                    ctx.block_terminated = true;
                }
            }

            Stmt::Match { expr, arms, .. } => {
                let (scrut_v, scrut_t) = Self::lower_expr(out, expr, ctx, None);
                if scrut_t.starts_with("{ i1, ") && arms.len() >= 2 {
                    let inner_ty = scrut_t
                        .trim_start_matches("{ i1, ")
                        .trim_end_matches(" }")
                        .to_string();
                    let tag_reg = ctx.next_reg();
                    out.push_str(&format!(
                        "  {} = extractvalue {} {}, 0\n",
                        tag_reg, scrut_t, scrut_v
                    ));
                    let id = ctx.next_label_id();
                    let ok_lbl = format!("match.ok.{}", id);
                    let err_lbl = format!("match.err.{}", id);
                    let end_lbl = format!("match.end.{}", id);

                    // Identifica qual braço é Some/Ok (tag == 1) e qual é None/Err (tag == 0)
                    let first_is_some_or_ok = match &arms[0].pattern {
                        MatchPattern::Variant { variant, .. } => {
                            matches!(variant.as_str(), "Some" | "Ok")
                        }
                        _ => true,
                    };
                    let (some_arm, none_arm) = if first_is_some_or_ok {
                        (&arms[0], &arms[1])
                    } else {
                        (&arms[1], &arms[0])
                    };

                    out.push_str(&format!(
                        "  br i1 {}, label %{}, label %{}\n",
                        tag_reg, ok_lbl, err_lbl
                    ));

                    // Braço Some / Ok
                    out.push_str(&format!("{}:\n", ok_lbl));
                    ctx.block_terminated = false;
                    if let MatchPattern::Variant {
                        binding: Some(b), ..
                    } = &some_arm.pattern
                    {
                        let pay_reg = ctx.next_reg();
                        out.push_str(&format!(
                            "  {} = extractvalue {} {}, 1\n",
                            pay_reg, scrut_t, scrut_v
                        ));
                        let slot = ctx.next_reg();
                        out.push_str(&format!("  {} = alloca {}, align 4\n", slot, inner_ty));
                        out.push_str(&format!(
                            "  store {} {}, ptr {}, align 4\n",
                            inner_ty, pay_reg, slot
                        ));
                        ctx.var_ptrs.insert(b.clone(), (slot, inner_ty.clone()));
                    }
                    for s in &some_arm.body {
                        if ctx.block_terminated {
                            break;
                        }
                        Self::lower_stmt(out, s, ctx, fn_ret);
                    }
                    let ok_term = ctx.block_terminated;
                    if !ok_term {
                        out.push_str(&format!("  br label %{}\n", end_lbl));
                    }

                    // Braço None / Err
                    out.push_str(&format!("{}:\n", err_lbl));
                    ctx.block_terminated = false;
                    if let MatchPattern::Variant {
                        binding: Some(b), ..
                    } = &none_arm.pattern
                    {
                        let slot = ctx.next_reg();
                        out.push_str(&format!("  {} = alloca i32, align 4\n", slot));
                        out.push_str(&format!("  store i32 0, ptr {}, align 4\n", slot));
                        ctx.var_ptrs.insert(b.clone(), (slot, "i32".to_string()));
                    }
                    for s in &none_arm.body {
                        if ctx.block_terminated {
                            break;
                        }
                        Self::lower_stmt(out, s, ctx, fn_ret);
                    }
                    let err_term = ctx.block_terminated;
                    if !err_term {
                        out.push_str(&format!("  br label %{}\n", end_lbl));
                    }

                    if !ok_term || !err_term {
                        out.push_str(&format!("{}:\n", end_lbl));
                        ctx.block_terminated = false;
                    }
                } else if let Some(first_arm) = arms.first() {
                    if let MatchPattern::Variant {
                        binding: Some(b), ..
                    } = &first_arm.pattern
                    {
                        let slot = ctx.next_reg();
                        out.push_str(&format!("  {} = alloca {}, align 4\n", slot, scrut_t));
                        out.push_str(&format!(
                            "  store {} {}, ptr {}, align 4\n",
                            scrut_t, scrut_v, slot
                        ));
                        ctx.var_ptrs.insert(b.clone(), (slot, scrut_t));
                    }
                    for s in &first_arm.body {
                        if ctx.block_terminated {
                            break;
                        }
                        Self::lower_stmt(out, s, ctx, fn_ret);
                    }
                }
            }

            Stmt::Return {
                value: expr_opt, ..
            } => {
                if let Some(e) = expr_opt {
                    let (v, t) = Self::lower_expr(out, e, ctx, fn_ret.as_deref());
                    let ret_t = fn_ret.clone().unwrap_or(t.clone());
                    let coerced = Self::coerce_scalar(out, ctx, &v, &t, &ret_t);
                    out.push_str(&format!("  ret {} {}\n", ret_t, coerced));
                } else if fn_ret.as_deref() == Some("i32") {
                    out.push_str("  ret i32 0\n");
                } else {
                    out.push_str("  ret void\n");
                }
                ctx.block_terminated = true;
            }

            Stmt::ExprStmt { expr: e, .. } => {
                let _ = Self::lower_expr(out, e, ctx, None);
            }
        }
    }

    fn lower_expr(
        out: &mut String,
        expr: &Expr,
        ctx: &mut LlvmLoweringCtx,
        expected_ty: Option<&str>,
    ) -> (String, String) {
        match expr {
            Expr::IntLit(v, _) => {
                let ty = match expected_ty {
                    Some(t @ ("i8" | "i16" | "i32" | "i64")) => t.to_string(),
                    _ => "i32".to_string(),
                };
                (v.to_string(), ty)
            }
            Expr::FloatLit(v, _) => {
                let ty = match expected_ty {
                    Some("double") => "double".to_string(),
                    _ => "float".to_string(),
                };
                let lit = Self::format_llvm_float(*v, &ty);
                (lit, ty)
            }
            Expr::BoolLit(b, _) => (if *b { "1".to_string() } else { "0".to_string() }, "i1".to_string()),
            Expr::StringLit(s, _) => {
                let (glob, _) = ctx.intern_string(s);
                (glob, "ptr".to_string())
            }
            Expr::Ident(name, _) => {
                if name == "None" {
                    if let Some(exp) = expected_ty {
                        if exp.starts_with('{') {
                            return ("zeroinitializer".to_string(), exp.to_string());
                        }
                    }
                    return ("zeroinitializer".to_string(), "{ i1, float }".to_string());
                }
                if let Some((slot, ty)) = ctx.var_ptrs.get(name).cloned() {
                    if ty.starts_with('[') {
                        return (slot, ty);
                    }
                    let r = ctx.next_reg();
                    out.push_str(&format!("  {} = load {}, ptr {}, align 4\n", r, ty, slot));
                    return (r, ty);
                }
                if let Some((reg, ty)) = ctx.param_vals.get(name).cloned() {
                    return (reg, ty);
                }
                ("0".to_string(), "i32".to_string())
            }
            Expr::Unary { op, expr: inner, .. } => match op {
                UnaryOp::Neg => {
                    if let Expr::IntLit(v, _) = inner.as_ref() {
                        let ty = match expected_ty {
                            Some(t @ ("i8" | "i16" | "i32" | "i64")) => t.to_string(),
                            _ => "i32".to_string(),
                        };
                        return (format!("-{}", v), ty);
                    }
                    let (in_v, in_t) = Self::lower_expr(out, inner, ctx, expected_ty);
                    let r = ctx.next_reg();
                    if in_t == "float" || in_t == "double" {
                        out.push_str(&format!("  {} = fneg fast {} {}\n", r, in_t, in_v));
                    } else {
                        out.push_str(&format!("  {} = sub {} 0, {}\n", r, in_t, in_v));
                    }
                    (r, in_t)
                }
                UnaryOp::Not => {
                    let (in_v, in_t) = Self::lower_expr(out, inner, ctx, Some("i1"));
                    let i1_v = Self::ensure_i1(out, ctx, &in_v, &in_t);
                    let r = ctx.next_reg();
                    out.push_str(&format!("  {} = xor i1 {}, true\n", r, i1_v));
                    (r, "i1".to_string())
                }
            },
            Expr::Binary {
                left, op, right, ..
            } => {
                let (l_v, l_t) = Self::lower_expr(out, left, ctx, expected_ty);
                let (r_v, r_t) = Self::lower_expr(out, right, ctx, Some(&l_t));
                let is_float = l_t == "float"
                    || l_t == "double"
                    || r_t == "float"
                    || r_t == "double"
                    || l_t.starts_with("%rts_")
                    || r_t.starts_with("%rts_");
                let common_ty = if is_float {
                    if l_t == "double" || r_t == "double" {
                        "double".to_string()
                    } else {
                        "float".to_string()
                    }
                } else if l_t == "i64" || r_t == "i64" {
                    "i64".to_string()
                } else {
                    l_t.clone()
                };

                let lhs = Self::coerce_scalar(out, ctx, &l_v, &l_t, &common_ty);
                let rhs = Self::coerce_scalar(out, ctx, &r_v, &r_t, &common_ty);
                let dst = ctx.next_reg();

                match op {
                    BinaryOp::Add => {
                        if is_float {
                            out.push_str(&format!(
                                "  {} = fadd fast {} {}, {}\n",
                                dst, common_ty, lhs, rhs
                            ));
                        } else {
                            out.push_str(&format!(
                                "  {} = add {} {}, {}\n",
                                dst, common_ty, lhs, rhs
                            ));
                        }
                        (dst, common_ty)
                    }
                    BinaryOp::Sub => {
                        if is_float {
                            out.push_str(&format!(
                                "  {} = fsub fast {} {}, {}\n",
                                dst, common_ty, lhs, rhs
                            ));
                        } else {
                            out.push_str(&format!(
                                "  {} = sub {} {}, {}\n",
                                dst, common_ty, lhs, rhs
                            ));
                        }
                        (dst, common_ty)
                    }
                    BinaryOp::Mul => {
                        if is_float {
                            out.push_str(&format!(
                                "  {} = fmul fast {} {}, {}\n",
                                dst, common_ty, lhs, rhs
                            ));
                        } else {
                            out.push_str(&format!(
                                "  {} = mul {} {}, {}\n",
                                dst, common_ty, lhs, rhs
                            ));
                        }
                        (dst, common_ty)
                    }
                    BinaryOp::Div => {
                        if is_float {
                            out.push_str(&format!(
                                "  {} = fdiv fast {} {}, {}\n",
                                dst, common_ty, lhs, rhs
                            ));
                        } else {
                            out.push_str(&format!(
                                "  {} = sdiv {} {}, {}\n",
                                dst, common_ty, lhs, rhs
                            ));
                        }
                        (dst, common_ty)
                    }
                    BinaryOp::Eq
                    | BinaryOp::NotEq
                    | BinaryOp::Lt
                    | BinaryOp::LtEq
                    | BinaryOp::Gt
                    | BinaryOp::GtEq => {
                        if is_float {
                            let pred = match op {
                                BinaryOp::Eq => "oeq",
                                BinaryOp::NotEq => "one",
                                BinaryOp::Lt => "olt",
                                BinaryOp::LtEq => "ole",
                                BinaryOp::Gt => "ogt",
                                BinaryOp::GtEq => "oge",
                                _ => "oeq",
                            };
                            out.push_str(&format!(
                                "  {} = fcmp fast {} {} {}, {}\n",
                                dst, pred, common_ty, lhs, rhs
                            ));
                        } else {
                            let pred = match op {
                                BinaryOp::Eq => "eq",
                                BinaryOp::NotEq => "ne",
                                BinaryOp::Lt => "slt",
                                BinaryOp::LtEq => "sle",
                                BinaryOp::Gt => "sgt",
                                BinaryOp::GtEq => "sge",
                                _ => "eq",
                            };
                            out.push_str(&format!(
                                "  {} = icmp {} {} {}, {}\n",
                                dst, pred, common_ty, lhs, rhs
                            ));
                        }
                        (dst, "i1".to_string())
                    }
                    BinaryOp::And => {
                        let l_i1 = Self::ensure_i1(out, ctx, &l_v, &l_t);
                        let r_i1 = Self::ensure_i1(out, ctx, &r_v, &r_t);
                        out.push_str(&format!("  {} = and i1 {}, {}\n", dst, l_i1, r_i1));
                        (dst, "i1".to_string())
                    }
                    BinaryOp::Or => {
                        let l_i1 = Self::ensure_i1(out, ctx, &l_v, &l_t);
                        let r_i1 = Self::ensure_i1(out, ctx, &r_v, &r_t);
                        out.push_str(&format!("  {} = or i1 {}, {}\n", dst, l_i1, r_i1));
                        (dst, "i1".to_string())
                    }
                }
            }

            Expr::FieldAccess {
                receiver, field, ..
            } => {
                // Caso A: Leitura de coluna SoA `pos[i].py`
                if let Expr::Index {
                    receiver: col_expr,
                    index,
                    ..
                } = receiver.as_ref()
                {
                    if let Expr::Ident(col_name, _) = col_expr.as_ref() {
                        if let Some(comp_name) = ctx.soa_columns.get(col_name).cloned() {
                            let field_idx = ctx
                                .component_soa_fields
                                .get(&(comp_name.clone(), field.clone()))
                                .copied()
                                .unwrap_or(0);
                            let col_reg = ctx
                                .param_vals
                                .get(col_name)
                                .map(|(r, _)| r.clone())
                                .unwrap_or_else(|| format!("%arg_{}", col_name));
                            let (idx_v, idx_t) = Self::lower_expr(out, index, ctx, Some("i64"));
                            let idx_64 = Self::ensure_i64(out, ctx, &idx_v, &idx_t);

                            let field_ptr_gep = ctx.next_reg();
                            out.push_str(&format!(
                                "  {} = getelementptr inbounds %{}_soa_column_t, ptr {}, i32 0, i32 {}\n",
                                field_ptr_gep, comp_name, col_reg, field_idx
                            ));
                            let base_ptr = ctx.next_reg();
                            out.push_str(&format!(
                                "  {} = load ptr, ptr {}, align 8\n",
                                base_ptr, field_ptr_gep
                            ));
                            let elem_gep = ctx.next_reg();
                            out.push_str(&format!(
                                "  {} = getelementptr inbounds float, ptr {}, i64 {}\n",
                                elem_gep, base_ptr, idx_64
                            ));
                            let val_reg = ctx.next_reg();
                            out.push_str(&format!(
                                "  {} = load float, ptr {}, align 4\n",
                                val_reg, elem_gep
                            ));
                            return (val_reg, "float".to_string());
                        }
                    }
                }

                // Caso B: `time.fixed_delta`
                if field == "fixed_delta" {
                    let (rec_v, _) = Self::lower_expr(out, receiver, ctx, None);
                    let gep = ctx.next_reg();
                    out.push_str(&format!(
                        "  {} = getelementptr inbounds %TimeStep_t, ptr {}, i32 0, i32 0\n",
                        gep, rec_v
                    ));
                    let val = ctx.next_reg();
                    out.push_str(&format!("  {} = load float, ptr {}, align 4\n", val, gep));
                    return (val, "float".to_string());
                }

                // Caso C: Struct local `tele.id` ou `self.temperatura`
                if let Expr::Ident(r_name, _) = receiver.as_ref() {
                    if let Some(s_name) = ctx.local_struct_names.get(r_name).cloned() {
                        if let Some((f_idx, f_ty)) =
                            ctx.struct_field_indices.get(&(s_name.clone(), field.clone())).cloned()
                        {
                            if let Some((slot, _)) = ctx.var_ptrs.get(r_name).cloned() {
                                let gep = ctx.next_reg();
                                out.push_str(&format!(
                                    "  {} = getelementptr inbounds %{}_t, ptr {}, i32 0, i32 {}\n",
                                    gep, s_name, slot, f_idx
                                ));
                                let val = ctx.next_reg();
                                out.push_str(&format!(
                                    "  {} = load {}, ptr {}, align 4\n",
                                    val, f_ty, gep
                                ));
                                return (val, f_ty);
                            }
                        }
                    }
                    if matches!(field.as_str(), "x" | "y" | "z" | "w") {
                        if let Some((slot, v_ty)) = ctx.var_ptrs.get(r_name).cloned() {
                            let lane_idx = match field.as_str() {
                                "x" => 0,
                                "y" => 1,
                                "z" => 2,
                                _ => 3,
                            };
                            let gep = ctx.next_reg();
                            out.push_str(&format!(
                                "  {} = getelementptr inbounds {}, ptr {}, i32 0, i32 {}\n",
                                gep, v_ty, slot, lane_idx
                            ));
                            let val = ctx.next_reg();
                            out.push_str(&format!(
                                "  {} = load float, ptr {}, align 4\n",
                                val, gep
                            ));
                            return (val, "float".to_string());
                        }
                    }
                }

                ("0.0".to_string(), "float".to_string())
            }

            Expr::Index {
                receiver, index, ..
            } => {
                if let Expr::Ident(arr_name, _) = receiver.as_ref() {
                    if let Some((slot, arr_ty)) = ctx.var_ptrs.get(arr_name).cloned() {
                        if arr_ty.starts_with('[') {
                            let elem_ty = arr_ty
                                .split(" x ")
                                .nth(1)
                                .map(|s| s.trim_end_matches(']').to_string())
                                .unwrap_or_else(|| "float".to_string());
                            let (idx_v, idx_t) = Self::lower_expr(out, index, ctx, Some("i64"));
                            let idx_64 = Self::ensure_i64(out, ctx, &idx_v, &idx_t);
                            let gep = ctx.next_reg();
                            out.push_str(&format!(
                                "  {} = getelementptr inbounds {}, ptr {}, i64 0, i64 {}\n",
                                gep, arr_ty, slot, idx_64
                            ));
                            let val = ctx.next_reg();
                            out.push_str(&format!(
                                "  {} = load {}, ptr {}, align 4\n",
                                val, elem_ty, gep
                            ));
                            return (val, elem_ty);
                        }
                    }
                }
                ("0.0".to_string(), "float".to_string())
            }

            Expr::MethodCall {
                receiver,
                method,
                args,
                ..
            } => {
                if method == "len" {
                    if let Expr::Ident(col_name, _) = receiver.as_ref() {
                        if let Some(comp_name) = ctx.soa_columns.get(col_name).cloned() {
                            let count_field_idx = ctx
                                .component_soa_fields
                                .iter()
                                .filter(|((c, f), _)| c == &comp_name && !f.contains('.'))
                                .map(|(_, idx)| *idx)
                                .max()
                                .unwrap_or(0)
                                + 2;
                            let col_reg = ctx
                                .param_vals
                                .get(col_name)
                                .map(|(r, _)| r.clone())
                                .unwrap_or_else(|| format!("%arg_{}", col_name));
                            let gep = ctx.next_reg();
                            out.push_str(&format!(
                                "  {} = getelementptr inbounds %{}_soa_column_t, ptr {}, i32 0, i32 {}\n",
                                gep, comp_name, col_reg, count_field_idx
                            ));
                            let cnt = ctx.next_reg();
                            out.push_str(&format!("  {} = load i64, ptr {}, align 8\n", cnt, gep));
                            return (cnt, "i64".to_string());
                        }
                    }
                    return ("0".to_string(), "i64".to_string());
                }

                if ctx.module_fn_names.contains(method) {
                    let (rec_v, rec_t) = Self::lower_expr(out, receiver, ctx, None);
                    let mut call_args = vec![format!("{} {}", rec_t, rec_v)];
                    let param_tys = ctx.fn_param_types.get(method).cloned().unwrap_or_default();
                    for (i, a) in args.iter().enumerate() {
                        let exp = param_tys.get(i + 1).map(|s| s.as_str());
                        let (av, at) = Self::lower_expr(out, a, ctx, exp);
                        let target_t = exp.unwrap_or(&at);
                        let coerced = Self::coerce_scalar(out, ctx, &av, &at, target_t);
                        call_args.push(format!("{} {}", target_t, coerced));
                    }
                    let callee = format!("{}_{}", ctx.mod_prefix, method);
                    if let Some(Some(ret_t)) = ctx.fn_return_types.get(method).cloned() {
                        let dst = ctx.next_reg();
                        out.push_str(&format!(
                            "  {} = call {} @{}({})\n",
                            dst,
                            ret_t,
                            callee,
                            call_args.join(", ")
                        ));
                        return (dst, ret_t);
                    } else {
                        out.push_str(&format!(
                            "  call void @{}({})\n",
                            callee,
                            call_args.join(", ")
                        ));
                        return ("0".to_string(), "i32".to_string());
                    }
                }

                for a in args {
                    let _ = Self::lower_expr(out, a, ctx, None);
                }
                ("0".to_string(), "i32".to_string())
            }

            Expr::StaticCall {
                namespace,
                func,
                args,
                ..
            } => {
                // 1. Console Intrinsics (`io::println`, `io::print_f32`, `io::print_i32`, `io::print_u32`)
                if namespace == "io" {
                    match func.as_str() {
                        "println" if args.len() == 1 => {
                            let (s_v, _) = Self::lower_expr(out, &args[0], ctx, Some("ptr"));
                            let dst = ctx.next_reg();
                            out.push_str(&format!(
                                "  {} = call i32 (ptr, ...) @printf(ptr @.str.fmt_ln, ptr {})\n",
                                dst, s_v
                            ));
                            return (dst, "i32".to_string());
                        }
                        "print_f32" if args.len() == 2 => {
                            let (s_v, _) = Self::lower_expr(out, &args[0], ctx, Some("ptr"));
                            let (f_v, f_t) = Self::lower_expr(out, &args[1], ctx, Some("float"));
                            let f_dbl = if f_t == "double" {
                                f_v
                            } else {
                                let ext = ctx.next_reg();
                                out.push_str(&format!(
                                    "  {} = fpext float {} to double\n",
                                    ext, f_v
                                ));
                                ext
                            };
                            let dst = ctx.next_reg();
                            out.push_str(&format!(
                                "  {} = call i32 (ptr, ...) @printf(ptr @.str.fmt_f32, ptr {}, double {})\n",
                                dst, s_v, f_dbl
                            ));
                            return (dst, "i32".to_string());
                        }
                        "print_i32" | "print_u32" if args.len() == 2 => {
                            let fmt_glob = if func == "print_i32" {
                                "@.str.fmt_i32"
                            } else {
                                "@.str.fmt_u32"
                            };
                            let (s_v, _) = Self::lower_expr(out, &args[0], ctx, Some("ptr"));
                            let (i_v, i_t) = Self::lower_expr(out, &args[1], ctx, Some("i32"));
                            let i_32 = Self::coerce_scalar(out, ctx, &i_v, &i_t, "i32");
                            let dst = ctx.next_reg();
                            out.push_str(&format!(
                                "  {} = call i32 (ptr, ...) @printf(ptr {}, ptr {}, i32 {})\n",
                                dst, fmt_glob, s_v, i_32
                            ));
                            return (dst, "i32".to_string());
                        }
                        _ => {}
                    }
                }

                // 2. Math Intrinsics (`math::sqrt`, `math::sin`, `math::cos`, `math::abs`, `math::clamp`, `math::lerp`)
                if namespace == "math" {
                    match func.as_str() {
                        "sqrt" | "sin" | "cos" | "abs" | "floor" | "ceil" | "round"
                            if args.len() == 1 =>
                        {
                            let intr = match func.as_str() {
                                "abs" => "@llvm.fabs.f32",
                                other => match other {
                                    "sqrt" => "@llvm.sqrt.f32",
                                    "sin" => "@llvm.sin.f32",
                                    "cos" => "@llvm.cos.f32",
                                    "floor" => "@llvm.floor.f32",
                                    "ceil" => "@llvm.ceil.f32",
                                    _ => "@llvm.round.f32",
                                },
                            };
                            let (a_v, a_t) = Self::lower_expr(out, &args[0], ctx, Some("float"));
                            let a_f32 = Self::coerce_scalar(out, ctx, &a_v, &a_t, "float");
                            let dst = ctx.next_reg();
                            out.push_str(&format!(
                                "  {} = call fast float {}(float {})\n",
                                dst, intr, a_f32
                            ));
                            return (dst, "float".to_string());
                        }
                        "clamp" if args.len() == 3 => {
                            let (x_v, x_t) = Self::lower_expr(out, &args[0], ctx, Some("float"));
                            let x = Self::coerce_scalar(out, ctx, &x_v, &x_t, "float");
                            let (lo_v, lo_t) = Self::lower_expr(out, &args[1], ctx, Some("float"));
                            let lo = Self::coerce_scalar(out, ctx, &lo_v, &lo_t, "float");
                            let (hi_v, hi_t) = Self::lower_expr(out, &args[2], ctx, Some("float"));
                            let hi = Self::coerce_scalar(out, ctx, &hi_v, &hi_t, "float");
                            let cmp_lo = ctx.next_reg();
                            out.push_str(&format!(
                                "  {} = fcmp fast olt float {}, {}\n",
                                cmp_lo, x, lo
                            ));
                            let max_lo = ctx.next_reg();
                            out.push_str(&format!(
                                "  {} = select i1 {}, float {}, float {}\n",
                                max_lo, cmp_lo, lo, x
                            ));
                            let cmp_hi = ctx.next_reg();
                            out.push_str(&format!(
                                "  {} = fcmp fast ogt float {}, {}\n",
                                cmp_hi, max_lo, hi
                            ));
                            let res = ctx.next_reg();
                            out.push_str(&format!(
                                "  {} = select i1 {}, float {}, float {}\n",
                                res, cmp_hi, hi, max_lo
                            ));
                            return (res, "float".to_string());
                        }
                        "lerp" if args.len() == 3 => {
                            let (a_v, a_t) = Self::lower_expr(out, &args[0], ctx, Some("float"));
                            let a = Self::coerce_scalar(out, ctx, &a_v, &a_t, "float");
                            let (b_v, b_t) = Self::lower_expr(out, &args[1], ctx, Some("float"));
                            let b = Self::coerce_scalar(out, ctx, &b_v, &b_t, "float");
                            let (t_v, t_t) = Self::lower_expr(out, &args[2], ctx, Some("float"));
                            let t = Self::coerce_scalar(out, ctx, &t_v, &t_t, "float");
                            let diff = ctx.next_reg();
                            out.push_str(&format!("  {} = fsub fast float {}, {}\n", diff, b, a));
                            let fma = ctx.next_reg();
                            out.push_str(&format!(
                                "  {} = call fast float @llvm.fmuladd.f32(float {}, float {}, float {})\n",
                                fma, diff, t, a
                            ));
                            return (fma, "float".to_string());
                        }
                        _ => {}
                    }
                }

                // 3. Construtores algébricos `Some(x)`, `Ok(x)`, `Err(e)` e vetoriais `vec2..quat`
                if (namespace == "self" || namespace == "Option" || namespace == "Result")
                    && matches!(func.as_str(), "Some" | "Ok" | "Err")
                    && args.len() == 1
                {
                    let inner_hint = expected_ty.and_then(|t| {
                        t.strip_prefix("{ i1, ").and_then(|s| s.strip_suffix(" }"))
                    });
                    let (pay_v, pay_t) = Self::lower_expr(out, &args[0], ctx, inner_hint);
                    let val_ty = inner_hint.unwrap_or(&pay_t);
                    let coerced = Self::coerce_scalar(out, ctx, &pay_v, &pay_t, val_ty);
                    let opt_ty = format!("{{ i1, {} }}", val_ty);
                    if func == "Err" {
                        return ("zeroinitializer".to_string(), opt_ty);
                    }
                    let r0 = ctx.next_reg();
                    out.push_str(&format!(
                        "  {} = insertvalue {} zeroinitializer, i1 1, 0\n",
                        r0, opt_ty
                    ));
                    let r1 = ctx.next_reg();
                    out.push_str(&format!(
                        "  {} = insertvalue {} {}, {} {}, 1\n",
                        r1, opt_ty, r0, val_ty, coerced
                    ));
                    return (r1, opt_ty);
                }

                if namespace == "self"
                    && matches!(func.as_str(), "vec2" | "vec3" | "vec4" | "quat")
                {
                    let vec_ty = format!("%rts_{}_t", func);
                    let mut cur_val = "undef".to_string();
                    for (idx, a) in args.iter().enumerate() {
                        let (av, at) = Self::lower_expr(out, a, ctx, Some("float"));
                        let af = Self::coerce_scalar(out, ctx, &av, &at, "float");
                        let next_val = ctx.next_reg();
                        out.push_str(&format!(
                            "  {} = insertvalue {} {}, float {}, {}\n",
                            next_val, vec_ty, cur_val, af, idx
                        ));
                        cur_val = next_val;
                    }
                    return (cur_val, vec_ty);
                }

                // 4. Chamadas FFI `extern "C" fn` (remove argumentos `cap` fantasmas)
                if let Some((cap_mask, ffi_tys, ret_opt)) = ctx.extern_fns.get(func).cloned() {
                    let mut ffi_args = Vec::new();
                    let mut ffi_idx = 0usize;
                    for (i, a) in args.iter().enumerate() {
                        if cap_mask.get(i).copied().unwrap_or(false) {
                            continue;
                        }
                        let exp = ffi_tys.get(ffi_idx).map(|s| s.as_str());
                        let (av, at) = Self::lower_expr(out, a, ctx, exp);
                        let target_t = exp.unwrap_or(&at);
                        let coerced = Self::coerce_scalar(out, ctx, &av, &at, target_t);
                        ffi_args.push(format!("{} {}", target_t, coerced));
                        ffi_idx += 1;
                    }
                    if let Some(ret_t) = ret_opt {
                        let dst = ctx.next_reg();
                        out.push_str(&format!(
                            "  {} = call {} @{}({})\n",
                            dst,
                            ret_t,
                            func,
                            ffi_args.join(", ")
                        ));
                        return (dst, ret_t);
                    } else {
                        out.push_str(&format!(
                            "  call void @{}({})\n",
                            func,
                            ffi_args.join(", ")
                        ));
                        return ("0".to_string(), "i32".to_string());
                    }
                }

                // 5. Funções do módulo ou métodos estáticos `Struct::metodo`
                if ctx.module_fn_names.contains(func) {
                    let param_tys = ctx.fn_param_types.get(func).cloned().unwrap_or_default();
                    let mut call_args = Vec::new();
                    for (i, a) in args.iter().enumerate() {
                        let exp = param_tys.get(i).map(|s| s.as_str());
                        let (av, at) = Self::lower_expr(out, a, ctx, exp);
                        let target_t = exp.unwrap_or(&at);
                        let coerced = Self::coerce_scalar(out, ctx, &av, &at, target_t);
                        call_args.push(format!("{} {}", target_t, coerced));
                    }
                    let callee = format!("{}_{}", ctx.mod_prefix, func);
                    if let Some(Some(ret_t)) = ctx.fn_return_types.get(func).cloned() {
                        let dst = ctx.next_reg();
                        out.push_str(&format!(
                            "  {} = call {} @{}({})\n",
                            dst,
                            ret_t,
                            callee,
                            call_args.join(", ")
                        ));
                        return (dst, ret_t);
                    } else {
                        out.push_str(&format!(
                            "  call void @{}({})\n",
                            callee,
                            call_args.join(", ")
                        ));
                        return ("0".to_string(), "i32".to_string());
                    }
                }

                ("0".to_string(), "i32".to_string())
            }

            Expr::StructInit {
                struct_name,
                fields,
                ..
            } => {
                let s_ty = format!("%{}_t", struct_name);
                let mut cur_val = "zeroinitializer".to_string();
                for (f_name, f_expr) in fields {
                    if let Some((f_idx, f_ty)) = ctx
                        .struct_field_indices
                        .get(&(struct_name.clone(), f_name.clone()))
                        .cloned()
                    {
                        let (fv, ft) = Self::lower_expr(out, f_expr, ctx, Some(&f_ty));
                        let coerced = Self::coerce_scalar(out, ctx, &fv, &ft, &f_ty);
                        let next_val = ctx.next_reg();
                        out.push_str(&format!(
                            "  {} = insertvalue {} {}, {} {}, {}\n",
                            next_val, s_ty, cur_val, f_ty, coerced, f_idx
                        ));
                        cur_val = next_val;
                    }
                }
                (cur_val, s_ty)
            }

            Expr::Cast {
                expr: inner,
                target_type,
                ..
            } => {
                let dst_ty = Self::map_llvm_type(target_type);
                let (in_v, in_t) = Self::lower_expr(out, inner, ctx, None);
                let coerced = Self::coerce_scalar(out, ctx, &in_v, &in_t, &dst_ty);
                (coerced, dst_ty)
            }

            Expr::EnumConstructor {
                variant,
                payload,
                ..
            } => {
                if variant == "None" || variant == "Err" {
                    let ty = expected_ty.unwrap_or("{ i1, float }").to_string();
                    return ("zeroinitializer".to_string(), ty);
                }
                if (variant == "Some" || variant == "Ok") && payload.is_some() {
                    let inner_hint = expected_ty.and_then(|t| {
                        t.strip_prefix("{ i1, ").and_then(|s| s.strip_suffix(" }"))
                    });
                    let p = payload.as_ref().unwrap();
                    let (pay_v, pay_t) = Self::lower_expr(out, p, ctx, inner_hint);
                    let val_ty = inner_hint.unwrap_or(&pay_t);
                    let coerced = Self::coerce_scalar(out, ctx, &pay_v, &pay_t, val_ty);
                    let opt_ty = format!("{{ i1, {} }}", val_ty);
                    let r0 = ctx.next_reg();
                    out.push_str(&format!(
                        "  {} = insertvalue {} zeroinitializer, i1 1, 0\n",
                        r0, opt_ty
                    ));
                    let r1 = ctx.next_reg();
                    out.push_str(&format!(
                        "  {} = insertvalue {} {}, {} {}, 1\n",
                        r1, opt_ty, r0, val_ty, coerced
                    ));
                    return (r1, opt_ty);
                }
                if let Some(p) = payload {
                    Self::lower_expr(out, p, ctx, expected_ty)
                } else {
                    ("0".to_string(), expected_ty.unwrap_or("i32").to_string())
                }
            }

            Expr::TryOp { expr: inner, .. } | Expr::ErrorMapClosure { body: inner, .. } => {
                Self::lower_expr(out, inner, ctx, expected_ty)
            }

            Expr::ArrayLit { .. } => ("zeroinitializer".to_string(), "ptr".to_string()),
        }
    }

    fn coerce_scalar(
        out: &mut String,
        ctx: &mut LlvmLoweringCtx,
        val: &str,
        from_ty: &str,
        to_ty: &str,
    ) -> String {
        if from_ty == to_ty {
            return val.to_string();
        }
        let is_from_int = matches!(from_ty, "i8" | "i16" | "i32" | "i64");
        let is_to_int = matches!(to_ty, "i8" | "i16" | "i32" | "i64");
        if is_from_int && is_to_int {
            let from_bits: u32 = from_ty[1..].parse().unwrap_or(32);
            let to_bits: u32 = to_ty[1..].parse().unwrap_or(32);
            let r = ctx.next_reg();
            if to_bits > from_bits {
                out.push_str(&format!(
                    "  {} = sext {} {} to {}\n",
                    r, from_ty, val, to_ty
                ));
            } else {
                out.push_str(&format!(
                    "  {} = trunc {} {} to {}\n",
                    r, from_ty, val, to_ty
                ));
            }
            return r;
        }
        if is_from_int && (to_ty == "float" || to_ty == "double") {
            let r = ctx.next_reg();
            out.push_str(&format!(
                "  {} = sitofp {} {} to {}\n",
                r, from_ty, val, to_ty
            ));
            return r;
        }
        if (from_ty == "float" || from_ty == "double") && is_to_int {
            let r = ctx.next_reg();
            out.push_str(&format!(
                "  {} = fptosi {} {} to {}\n",
                r, from_ty, val, to_ty
            ));
            return r;
        }
        if from_ty == "float" && to_ty == "double" {
            let r = ctx.next_reg();
            out.push_str(&format!("  {} = fpext float {} to double\n", r, val));
            return r;
        }
        if from_ty == "double" && to_ty == "float" {
            let r = ctx.next_reg();
            out.push_str(&format!("  {} = fptrunc double {} to float\n", r, val));
            return r;
        }
        if from_ty == "float" && to_ty.starts_with("%rts_") {
            let r = ctx.next_reg();
            out.push_str(&format!(
                "  {} = insertvalue {} zeroinitializer, float {}, 0\n",
                r, to_ty, val
            ));
            return r;
        }
        if from_ty.starts_with("%rts_") && to_ty == "float" {
            let r = ctx.next_reg();
            out.push_str(&format!(
                "  {} = extractvalue {} {}, 0\n",
                r, from_ty, val
            ));
            return r;
        }
        val.to_string()
    }

    fn ensure_i64(out: &mut String, ctx: &mut LlvmLoweringCtx, val: &str, ty: &str) -> String {
        Self::coerce_scalar(out, ctx, val, ty, "i64")
    }

    fn ensure_i1(out: &mut String, ctx: &mut LlvmLoweringCtx, val: &str, ty: &str) -> String {
        if ty == "i1" {
            return val.to_string();
        }
        let r = ctx.next_reg();
        out.push_str(&format!("  {} = icmp ne {} {}, 0\n", r, ty, val));
        r
    }

    fn format_llvm_float(v: f64, llvm_ty: &str) -> String {
        let exact_f32 = (v as f32) as f64;
        if exact_f32 == v && (v * 16.0).fract() == 0.0 {
            let s = format!("{:.1}", v);
            return s;
        }
        let bits = if llvm_ty == "double" {
            v.to_bits()
        } else {
            exact_f32.to_bits()
        };
        format!("0x{:016X}", bits)
    }

    fn escape_llvm_string(s: &str) -> String {
        let mut out = String::new();
        for b in s.bytes() {
            if (0x20..=0x7E).contains(&b) && b != b'"' && b != b'\\' {
                out.push(b as char);
            } else {
                out.push_str(&format!("\\{:02X}", b));
            }
        }
        out
    }

    fn map_param_llvm_type(p: &FnParam) -> String {
        if p.is_cap {
            "ptr".to_string()
        } else {
            Self::map_llvm_type(&p.ty)
        }
    }

    pub fn map_llvm_type(ty: &TypeExpr) -> String {
        match ty {
            TypeExpr::Primitive(p) => match p {
                PrimitiveType::I8 | PrimitiveType::U8 => "i8".to_string(),
                PrimitiveType::I16 | PrimitiveType::U16 => "i16".to_string(),
                PrimitiveType::I32 | PrimitiveType::U32 | PrimitiveType::Fix32 => "i32".to_string(),
                PrimitiveType::I64 | PrimitiveType::U64 | PrimitiveType::Usize => "i64".to_string(),
                PrimitiveType::F32 => "float".to_string(),
                PrimitiveType::F64 => "double".to_string(),
                PrimitiveType::Bool => "i1".to_string(),
                PrimitiveType::Str => "ptr".to_string(),
            },
            TypeExpr::Math(m) => match m {
                MathType::Vec2 => "%rts_vec2_t".to_string(),
                MathType::Vec3 => "%rts_vec3_t".to_string(),
                MathType::Vec4 => "%rts_vec4_t".to_string(),
                MathType::Quat => "%rts_quat_t".to_string(),
                MathType::Mat3 => "[9 x float]".to_string(),
                MathType::Mat4 => "[16 x float]".to_string(),
            },
            TypeExpr::Array(inner, len) => {
                format!("[{} x {}]", len, Self::map_llvm_type(inner))
            }
            TypeExpr::Handle(_) => "i64".to_string(),
            TypeExpr::Option(inner) => {
                format!("{{ i1, {} }}", Self::map_llvm_type(inner))
            }
            TypeExpr::Result(ok, _) => {
                format!("{{ i1, {} }}", Self::map_llvm_type(ok))
            }
            TypeExpr::Capability(_) => "ptr".to_string(),
            TypeExpr::Named { name, .. } => format!("%{}_t", name),
        }
    }
}
