    fn is_pure_select_expr(expr: &Expr) -> bool {
        match expr {
            Expr::IntLit(_, _)
            | Expr::FloatLit(_, _)
            | Expr::BoolLit(_, _)
            | Expr::StringLit(_, _)
            | Expr::Ident(_, _) => true,
            Expr::Unary { expr: inner, .. } => Self::is_pure_select_expr(inner),
            Expr::Cast { expr: inner, .. } => Self::is_pure_select_expr(inner),
            Expr::Binary {
                left, op, right, ..
            } => {
                !matches!(op, BinaryOp::Div | BinaryOp::Rem)
                    && Self::is_pure_select_expr(left)
                    && Self::is_pure_select_expr(right)
            }
            _ => false,
        }
    }

    fn coerce_cast_scalar(
        out: &mut String,
        ctx: &mut LlvmLoweringCtx,
        val: &str,
        from_ty: &str,
        to_ty: &str,
        src_unsigned: bool,
        dst_unsigned: bool,
    ) -> String {
        if from_ty == to_ty {
            return val.to_string();
        }
        let is_from_int = matches!(from_ty, "i8" | "i16" | "i32" | "i64");
        let is_to_int = matches!(to_ty, "i8" | "i16" | "i32" | "i64");
        if is_from_int && is_to_int {
            let from_bits: u32 = from_ty[1..].parse().unwrap_or(32);
            let to_bits: u32 = to_ty[1..].parse().unwrap_or(32);
            if to_bits > from_bits && src_unsigned {
                let r = ctx.next_reg();
                out.push_str(&format!(
                    "  {} = zext {} {} to {}\n",
                    r, from_ty, val, to_ty
                ));
                return r;
            }
        }
        if is_from_int && (to_ty == "float" || to_ty == "double") && src_unsigned {
            let r = ctx.next_reg();
            out.push_str(&format!(
                "  {} = uitofp {} {} to {}\n",
                r, from_ty, val, to_ty
            ));
            return r;
        }
        if (from_ty == "float" || from_ty == "double") && is_to_int && dst_unsigned {
            let r = ctx.next_reg();
            out.push_str(&format!(
                "  {} = fptoui {} {} to {}\n",
                r, from_ty, val, to_ty
            ));
            return r;
        }
        Self::coerce_scalar(out, ctx, val, from_ty, to_ty)
    }

    fn is_unsigned_type_expr(ty: &TypeExpr) -> bool {
        match ty {
            TypeExpr::Primitive(p) => matches!(
                p,
                PrimitiveType::U8
                    | PrimitiveType::U16
                    | PrimitiveType::U32
                    | PrimitiveType::U64
                    | PrimitiveType::Usize
            ),
            TypeExpr::Array(inner, _) => Self::is_unsigned_type_expr(inner),
            TypeExpr::Capability(cap) => cap
                .slice_element_type()
                .as_ref()
                .map_or(false, Self::is_unsigned_type_expr),
            _ => false,
        }
    }

    fn is_expr_unsigned(expr: &Expr, ctx: &LlvmLoweringCtx) -> bool {
        match expr {
            Expr::Ident(name, _) => ctx.unsigned_vars.contains(name),
            Expr::Index { receiver, .. } => {
                if let Expr::Ident(name, _) = receiver.as_ref() {
                    ctx.unsigned_vars.contains(name)
                } else {
                    false
                }
            }
            Expr::Cast { target_type, .. } => Self::is_unsigned_type_expr(target_type),
            Expr::Unary { expr: inner, .. } => Self::is_expr_unsigned(inner, ctx),
            Expr::Binary { left, right, .. } => {
                Self::is_expr_unsigned(left, ctx) || Self::is_expr_unsigned(right, ctx)
            }
            Expr::IfExpr {
                then_branch,
                else_branch,
                ..
            } => Self::is_expr_unsigned(then_branch, ctx) || Self::is_expr_unsigned(else_branch, ctx),
            _ => false,
        }
    }

    fn infer_llvm_expr_ty(expr: &Expr, ctx: &LlvmLoweringCtx) -> String {
        match expr {
            Expr::IntLit(_, _) => "i32".to_string(),
            Expr::FloatLit(_, _) => "float".to_string(),
            Expr::BoolLit(_, _) => "i1".to_string(),
            Expr::StringLit(_, _) => "ptr".to_string(),
            Expr::Ident(name, _) => {
                if let Some((_, ty)) = ctx.var_ptrs.get(name) {
                    return ty.clone();
                }
                if let Some((_, ty)) = ctx.param_vals.get(name) {
                    return ty.clone();
                }
                if let Some((_, ty)) = ctx.const_scalars.get(name) {
                    return ty.clone();
                }
                "i32".to_string()
            }
            Expr::Cast { target_type, .. } => Self::map_llvm_type(target_type),
            Expr::Unary { op, expr: inner, .. } => match op {
                UnaryOp::Not => "i1".to_string(),
                _ => Self::infer_llvm_expr_ty(inner, ctx),
            },
            Expr::Binary { left, op, right, .. } => match op {
                BinaryOp::Eq
                | BinaryOp::NotEq
                | BinaryOp::Lt
                | BinaryOp::LtEq
                | BinaryOp::Gt
                | BinaryOp::GtEq
                | BinaryOp::And
                | BinaryOp::Or => "i1".to_string(),
                _ => {
                    let lt = Self::infer_llvm_expr_ty(left, ctx);
                    let rt = Self::infer_llvm_expr_ty(right, ctx);
                    if lt == "double" || rt == "double" {
                        "double".to_string()
                    } else if lt == "float" || rt == "float" {
                        "float".to_string()
                    } else if lt == "i64" || rt == "i64" {
                        "i64".to_string()
                    } else {
                        lt
                    }
                }
            },
            Expr::IfExpr { then_branch, .. } => Self::infer_llvm_expr_ty(then_branch, ctx),
            _ => "i32".to_string(),
        }
    }

    fn fold_const_expr(expr: &Expr, known: &HashMap<String, Expr>) -> Expr {
        match expr {
            Expr::Ident(name, _) => known.get(name).cloned().unwrap_or_else(|| expr.clone()),
            Expr::Unary { op, expr: inner, span } => {
                let r = Self::fold_const_expr(inner, known);
                match (op, &r) {
                    (UnaryOp::Neg, Expr::FloatLit(v, _)) => Expr::FloatLit(-v, span.clone()),
                    (UnaryOp::Not, Expr::BoolLit(b, _)) => Expr::BoolLit(!b, span.clone()),
                    _ => Expr::Unary {
                        op: op.clone(),
                        expr: Box::new(r),
                        span: span.clone(),
                    },
                }
            }
            Expr::Binary {
                left,
                op,
                right,
                span,
            } => {
                let l = Self::fold_const_expr(left, known);
                let r = Self::fold_const_expr(right, known);
                if let (Expr::IntLit(a, _), Expr::IntLit(b, _)) = (&l, &r) {
                    match op {
                        BinaryOp::Add => return Expr::IntLit(a.wrapping_add(*b), span.clone()),
                        BinaryOp::Sub => return Expr::IntLit(a.wrapping_sub(*b), span.clone()),
                        BinaryOp::Mul => return Expr::IntLit(a.wrapping_mul(*b), span.clone()),
                        BinaryOp::Div if *b != 0 => return Expr::IntLit(a / b, span.clone()),
                        BinaryOp::Rem if *b != 0 => return Expr::IntLit(a % b, span.clone()),
                        BinaryOp::BitAnd => return Expr::IntLit(a & b, span.clone()),
                        BinaryOp::BitOr => return Expr::IntLit(a | b, span.clone()),
                        BinaryOp::BitXor => return Expr::IntLit(a ^ b, span.clone()),
                        BinaryOp::Shl => return Expr::IntLit(a.wrapping_shl(*b as u32), span.clone()),
                        BinaryOp::Shr => return Expr::IntLit(a.wrapping_shr(*b as u32), span.clone()),
                        BinaryOp::Eq => return Expr::BoolLit(a == b, span.clone()),
                        BinaryOp::NotEq => return Expr::BoolLit(a != b, span.clone()),
                        BinaryOp::Lt => return Expr::BoolLit(a < b, span.clone()),
                        BinaryOp::LtEq => return Expr::BoolLit(a <= b, span.clone()),
                        BinaryOp::Gt => return Expr::BoolLit(a > b, span.clone()),
                        BinaryOp::GtEq => return Expr::BoolLit(a >= b, span.clone()),
                        _ => {}
                    }
                }
                Expr::Binary {
                    left: Box::new(l),
                    op: op.clone(),
                    right: Box::new(r),
                    span: span.clone(),
                }
            }
            Expr::Cast {
                expr: inner,
                target_type,
                span,
            } => Expr::Cast {
                expr: Box::new(Self::fold_const_expr(inner, known)),
                target_type: target_type.clone(),
                span: span.clone(),
            },
            _ => expr.clone(),
        }
    }

    fn eval_const_llvm_lit(expr: &Expr, target_ll_ty: &str, known: &HashMap<String, Expr>) -> String {
        let folded = Self::fold_const_expr(expr, known);
        match folded {
            Expr::IntLit(v, _) => {
                if target_ll_ty == "float" || target_ll_ty == "double" {
                    Self::format_llvm_float(v as f64, target_ll_ty)
                } else {
                    v.to_string()
                }
            }
            Expr::FloatLit(v, _) => Self::format_llvm_float(v, target_ll_ty),
            Expr::BoolLit(b, _) => if b { "1" } else { "0" }.to_string(),
            Expr::Unary {
                op: UnaryOp::Neg,
                expr: inner,
                ..
            } => {
                if let Expr::IntLit(v, _) = inner.as_ref() {
                    if target_ll_ty == "float" || target_ll_ty == "double" {
                        Self::format_llvm_float(-(*v as f64), target_ll_ty)
                    } else {
                        format!("-{}", v)
                    }
                } else {
                    "0".to_string()
                }
            }
            Expr::Unary {
                op: UnaryOp::BitNot,
                expr: inner,
                ..
            } => {
                if let Expr::IntLit(v, _) = inner.as_ref() {
                    let res: i64 = match target_ll_ty {
                        "i8" => !(*v as i8) as i64,
                        "i16" => !(*v as i16) as i64,
                        "i64" => !(*v as i64),
                        _ => !(*v as i32) as i64,
                    };
                    res.to_string()
                } else {
                    "0".to_string()
                }
            }
            Expr::Cast { expr: inner, .. } => {
                Self::eval_const_llvm_lit(&inner, target_ll_ty, known)
            }
            _ => {
                if target_ll_ty == "float" || target_ll_ty == "double" {
                    "0.0".to_string()
                } else {
                    "0".to_string()
                }
            }
        }
    }
