/// Transpilador Nativo (`rtsc --target native` — v2.0.0-rts Generalized Native & Hardware Codegen)
/// Implementa:
/// 1. Descritores SoA compactos de 64B (1 linha de cache L1) e `vectorize(assume_safety)` apenas em loops lineares.
/// 2. Detecção de Scatter Indireto (`vel[entity_idx]`): suprime `assume_safety` quando o índice não é o iterador linear
///    e envolve escritas indiretas em guarda geracional (`Handle<T>`) + Bounds Check.
/// 3. Zero Nomes Mágicos: elimina hardcodes `"impacts_this_frame"` e `"time"`, usando cursores internos por arena
///    (`_rts_pushed_<arena>`) e rastreamento automático de parâmetros ponteiro (`ptr_params`).
/// 4. Lowering Real de `?` (`Expr::TryOp`), `.map_err(|_| ...)`, Enums com Payload e Capacidades de Hardware
///    (`I2CBus<Addr>`, `PWMPin<Channel>`, `MonotonicClock`), compilando `thermal_control.rts` nativamente.
pub struct NativeCodegen;

